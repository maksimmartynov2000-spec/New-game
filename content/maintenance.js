// Пока здесь стоит время В БУДУЩЕМ, приложение показывает заглушку и играть нельзя.
// Как только это время прошло — заглушка исчезает сама, второй раз мержить ничего
// не нужно. Именно поэтому здесь время окончания, а не выключатель «включено/выключено»:
// забытый выключатель запер бы учеников насовсем.
//
// ВКЛЮЧИТЬ: поставить в until момент, когда работы закончатся, по Гринвичу (UTC).
//           Москва — это UTC+3, то есть 18:30 по Москве это '2026-09-04T15:30:00Z'.
// ВЫКЛЮЧИТЬ ДОСРОЧНО: вернуть null.
//
// СКОЛЬКО СТАВИТЬ. Договорённость: большая правка — 20 минут, маленькая — 10.
// Больше не ставить. Экран запирает игру целиком, поэтому ошибаться лучше в
// короткую сторону: не успели — продлить одной правкой одной строки, а вот
// вернуть ученику полтора часа, когда он сел заниматься, уже нельзя.
// Большая — это то, что трогает хранение прогресса, генератор или загрузку
// приложения. Маленькая — экраны, тексты, оформление.
//
// note — строчка от себя, НА ЧЕТЫРЁХ ЯЗЫКАХ. Заголовок экрана и «приходи через
//        пять минут» переводятся сами, а эта строка — содержимое, и до этой правки
//        она была единственным русским текстом, который видел ученик на любом языке.
//        Видно её при этом чаще всего остального: экран работ показывается всем и
//        как раз после обновления. Убрать строку целиком — поставить null.
//
// Файл читается при каждом запуске и раз в полминуты во время работы, поэтому
// заглушка появляется у учеников сама, без переустановки приложения. Если файл
// не загрузился совсем — работы считаются выключенными: остаться без игры
// из-за оборвавшейся сети хуже, чем поиграть во время работ.

