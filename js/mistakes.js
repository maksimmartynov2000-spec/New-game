// Дробь ли это и равны ли две дроби по величине (а не по записи).
const isFrac = (v) => v && typeof v === 'object' && 'num' in v && 'den' in v;
const isDecimalValue = (v) => v && typeof v === 'object' && 'intVal' in v && 'dp' in v;
const sameValue = (x, y) => isFrac(x) && isFrac(y) && x.den !== 0 && y.den !== 0
    && x.num * y.den === y.num * x.den;
const sameFrac = (x, y) => isFrac(x) && isFrac(y) && x.num === y.num && x.den === y.den;

function classifyFractionArith(problem, correct, chosen) {
    const { f1, f2, opKey } = problem;
    if (!isFrac(chosen) || !isFrac(f1) || !isFrac(f2)) return null;

    // Величина верная, запись — нет. Если знаменатели были одинаковые, а ученик
    // всё равно перемножил их крест-накрест, это отдельная, очень характерная
    // история: не ошибка в счёте, а лишний шаг от неуверенности.
    if (sameValue(chosen, correct)) {
        if (f1.den === f2.den && chosen.den === f1.den * f2.den) return 'общий знаменатель зря';
        return 'не сократил';
    }

    if (chosen.num === -correct.num && chosen.den === correct.den) return 'ошибся в знаке';

    // «Сложил в лоб»: числители к числителям, знаменатели к знаменателям.
    const flat = opKey === 'sub'
        ? { num: f1.num - f2.num, den: f1.den - f2.den }
        : { num: f1.num + f2.num, den: f1.den + f2.den };
    if (flat.den !== 0 && (sameFrac(chosen, flat) || sameValue(chosen, flat))) return 'сложил знаменатели';
    // В вычитании с одинаковыми знаменателями «в лоб» даёт ноль в знаменателе, и доли
    // пропадают совсем: 5/7 − 2/7 = 3. Это та же ошибка — знаменатели вычтены тоже.
    if (opKey === 'sub' && f1.den === f2.den && chosen.den === 1 && chosen.num === f1.num - f2.num) return 'сложил знаменатели';

    // Деление без переворота второй дроби — то же самое, что умножение.
    if (opKey === 'div' && f2.num !== 0) {
        const asMul = fracMul(f1, f2);
        if (sameFrac(chosen, asMul) || sameValue(chosen, asMul)) return 'не перевернул дробь';
    }

    // Умножение: перемножил числители, а знаменатель взял из готового.
    if (opKey === 'mul') {
        const a = simplifyFrac(f1.num * f2.num, f1.den);
        const b = simplifyFrac(f1.num * f2.num, f2.den);
        if (sameFrac(chosen, a) || sameFrac(chosen, b)) return 'забыл перемножить знаменатели';
    }

    // Деление: перевернул первую дробь вместо второй.
    if (opKey === 'div' && f1.num !== 0 && f2.den !== 0) {
        const flipped = simplifyFrac(f1.den * f2.num, f1.num * f2.den);
        if (sameFrac(chosen, flipped)) return 'перевернул не ту дробь';
    }

    // Сложение и вычитание с разными знаменателями: привёл к общему только одну
    // дробь, а числитель второй взял как есть. Очень характерная половинчатая ошибка.
    if ((opKey === 'add' || opKey === 'sub') && f1.den !== f2.den) {
        const lcd = f1.den * f2.den / gcd(f1.den, f2.den);
        const sign = opKey === 'add' ? 1 : -1;
        const half1 = { num: f1.num * (lcd / f1.den) + sign * f2.num, den: lcd };
        const half2 = { num: f1.num + sign * f2.num * (lcd / f2.den), den: lcd };
        if (sameValue(chosen, half1) || sameValue(chosen, half2)) return 'перевёл не обе дроби';
    }

    const opposite = { add: 'sub', sub: 'add', mul: 'div', div: 'mul' }[opKey];
    if (opposite) {
        try {
            const other = opposite === 'add' ? fracAdd(f1, f2)
                : opposite === 'sub' ? fracSub(f1, f2)
                : opposite === 'mul' ? fracMul(f1, f2)
                : (f2.num !== 0 ? fracDiv(f1, f2) : null);
            if (other && (sameFrac(chosen, other) || sameValue(chosen, other))) return 'перепутал действие';
            // Сложение с одинаковыми знаменателями, где второе число больше: вычитая,
            // из большего вычитают меньшее (1/7 + 3/7 → 2/7).
            if (other && opposite === 'sub' && f1.den === f2.den && other.num < 0 && chosen.num > 0
                && sameValue(chosen, { num: -other.num, den: other.den })) return 'перепутал действие';
        } catch (e) { /* обратное действие неопределено — просто идём дальше */ }
    }

    // Ответ должен был быть смешанным числом, а взята только дробная часть.
    const m = toMixedParts(correct);
    if (m && m.whole !== 0 && m.remNum !== 0
        && Math.abs(chosen.num) === m.remNum && chosen.den === m.den) return 'забыл целую часть';

    // Сложение и вычитание с одинаковыми знаменателями: знаменатель тот же, числитель
    // на единицу больше или меньше — промах в счёте долей, а не в правиле: 3/7 + 1/7 = 5/7.
    if ((opKey === 'add' || opKey === 'sub') && f1.den === f2.den
        && chosen.den === correct.den && correct.den > 1 && Math.abs(chosen.num - correct.num) === 1) return 'ошибся на одну долю';

    return null;
}

// Разрядные правила («ошибка в десятках», «промахнулся рядом», «оба разряда
// мимо», «посчитал только единицы») говорят о ЧИСЛЕ и молчат о знаке. На
// отрицательных они правдивы ровно тогда, когда ответ и выбранное стоят по
// одну сторону от нуля, — это и проверяет sameSide.
//
// Раньше здесь стояло «только не для отрицательных», целиком. Это было честно,
// но слишком грубо: на отрицательных почти половина ошибок уходила в «другую
// ошибку» и молчала, хотя −5 × 5 = −25 против −75 — ровно та же ошибка в
// десятках, что и у положительных. А вот 10 × (−4) = −40 против 50 — нет:
// оба числа кончаются нулём, «единицы сошлись» формально, но ребёнок перепутал
// знак, и говорить ему про десятки было бы выдумкой. Замер на ловушках
// генератора: без этого условия текст про десятки врал в 14,5% случаев.
//
// Ноль стороны не имеет: с ним сравнивать знак не с чем, и правило решает само.
// Для положительных sameSide всегда истинно — там всё работает как прежде.
function classifyIntegerLike(problem, correct, chosen, opKey, isNegative) {
    if (typeof chosen !== 'number' || typeof correct !== 'number') return null;
    const a = problem.a, b = problem.b;
    // Три множителя хранятся как два числа — произведение первых двух и третье.
    // Правила ниже, которые разбирают пример как «a × b», на них врут: соседняя
    // клетка «−14 × −10», «посчитано только 3 × 4», «12, взятое −4 раза» — всё это
    // числа, которых ребёнок не видел. Поэтому для тройных их просто нет. Правила,
    // которые смотрят только на ответ и выбранное, работают как прежде.
    const haveOperands = typeof a === 'number' && typeof b === 'number' && !problem.triple;
    const sameSide = !isNegative || chosen === 0 || correct === 0
        || Math.sign(chosen) === Math.sign(correct);

    if (chosen === -correct && correct !== 0) return 'ошибся в знаке';

    // Отрицательные сложение и вычитание: типичная ошибка темы — та же модель,
    // по которой строится вторая пара вариантов (см. negTypicalMag). Знак у
    // такого ответа любой: ошибка в модуле, а знак — отдельное дело.
    //  - без скобок: модули сложены, а надо вычесть, или наоборот («−8 + 3 = −11»);
    //  - со скобками в вычитании: не замечен двойной минус («5 − (−3)» как 5 − 3);
    //  - со скобками в сложении: не замечен минус в скобке («5 + (−3)» как 5 + 3).
    // Скобки в записи бывают только у второго числа и только при его минусе,
    // поэтому действие тут совпадает с тем, что видно на экране.
    if (isNegative && (opKey === 'add' || opKey === 'sub') && haveOperands
        && typeof negTypicalMag === 'function') {
        const typ = negTypicalMag(opKey, a, b, correct, problem);
        if (typ && Math.abs(chosen) === typ) {
            if ((problem.text || '').indexOf('(') < 0) return 'спутал модули';
            return opKey === 'sub' ? 'двойной минус' : 'минус в скобках';
        }
    }

    // Единицы посчитаны верно, десятки — нет: 17 + 18 = 35, а названо 45 или 25.
    // Проверяем раньше остальных разрядных моделей, потому что это самая частая
    // ошибка и самая узкая примета — ровно десять мимо при верной последней цифре.
    // Ярлык «не перенёс десяток» остался в словаре ради старых записей в журнале,
    // но новые в него больше не пишутся: модель, по которой он ставился, считала
    // разряды все сразу и на двух переносах давала не ошибку, а мусор.
    if (sameSide && (opKey === 'add' || opKey === 'sub') && Math.abs(chosen - correct) === 10) {
        return 'ошибка в десятках';
    }

    // Разряды: вычел, не заняв десяток. Это та же модель, по которой строятся
    // варианты ответа, — см. buildDistractors.
    if (haveOperands) {
        if (opKey === 'sub') {
            const nb = noBorrowSub(a, b);
            if (nb !== null && (chosen === nb || chosen === -nb)) return 'не занял десяток';
            if (chosen === b - a && a !== b) return 'переставил числа';
        }

        const others = { add: a - b, sub: a + b, mul: (b !== 0 ? a / b : null), div: a * b };
        const other = others[opKey];
        if (other !== null && other !== undefined && chosen === other) return 'перепутал действие';
        if (opKey === 'mul' && chosen === a + b) return 'сложил вместо умножения';

        // Соседняя клетка таблицы умножения: 7×8 вместо 7×7.
        if (opKey === 'mul' && (chosen === a * (b + 1) || chosen === a * (b - 1)
            || chosen === (a + 1) * b || chosen === (a - 1) * b)) return 'таблица умножения';

        // При делении часто называют само делимое или делитель, не посчитав.
        if (opKey === 'div' && (chosen === a || chosen === b)) return 'взял одно из чисел';
    }

    // Промах на единицу проверяем последним: иначе он перехватывал бы более
    // говорящие причины, которые случайно оказались рядом с верным ответом.
    if (Math.abs(chosen - correct) === 1) return 'ошибся на единицу';

    // Зеркало «ошибки в десятках»: десятки верные, последняя цифра нет. Это вторая
    // половина столбикового счёта, и до сих пор она уходила в «другую ошибку» —
    // самую частую и самую бесполезную корзину на сложении и вычитании. По замеру
    // на шести тысячах неверных вариантов эта модель забирает из неё 46% на
    // сложении и 69% на вычитании.
    //
    // Ставится САМОЙ последней, ниже промаха на единицу: «34 вместо 35» это тоже
    // верные десятки при неверной единице, но там ученику полезнее услышать
    // «мимо на единицу». На отрицательных правило срабатывает, только когда оба
    // числа положительные (условие ниже) — это обычный столбик, и слова верны.
    //
    // Оба числа должны быть не меньше десяти. Без этого условия «9 вместо 7»
    // тоже считалось «верными десятками» — их там просто нет ни одного, — и
    // подсказка говорила «десятки сошлись» на первой звезде вычитания в ста
    // процентах случаев. Однозначный промах честнее оставить «другой ошибкой»:
    // про него мы действительно ничего не знаем.
    if ((opKey === 'add' || opKey === 'sub') && chosen >= 10 && correct >= 10
        && chosen % 10 !== correct % 10
        && Math.floor(chosen / 10) === Math.floor(correct / 10)) {
        return 'ошибка в единицах';
    }

    // Двузначное на однозначное умножают по частям: сначала на единицы, потом
    // на десятки, потом складывают. Пропустить вторую часть — ровно промах на
    // 10·(меньший множитель): 7 × 13 = 91, а посчитано 7 × 3 = 21. Это не
    // соседняя клетка таблицы и не случайный промах, а один конкретный
    // пропущенный шаг, и ловушка с таким числом ставится намеренно —
    // см. sameUnitsDecoy в генераторе.
    //
    // Только ВНИЗ. Тот же промах вверх означал бы лишний десяток, а не
    // потерянный, и объяснять его этими словами было бы неправдой; вверх
    // ловится общим правилом «та же последняя цифра» ниже. Круглый второй
    // множитель (7 × 20) исключён по той же причине: единиц у него нет,
    // и «посчитал только единицы» про него сказать нельзя.
    if (sameSide && haveOperands && opKey === 'mul') {
        const lo = Math.min(a, b), hi = Math.max(a, b);
        if (hi >= 11 && hi % 10 !== 0 && lo > 1 && lo <= 9
            && correct - chosen === 10 * lo) {
            return 'не умножил десятки';
        }
    }

    // Та же последняя цифра, другой десяток. У сложения это «ошибка в десятках»
    // и разбирается выше по точному промаху на десять; у умножения и деления
    // промах кратен десяти, но не равен ему (7 × 13 против 7 × 3 — это 70),
    // поэтому там нужна проверка по самой цифре. Ловушка эта тоже намеренная:
    // без второго числа с той же последней цифрой ответ берётся счётом одного
    // разряда из двух.
    if (sameSide && (opKey === 'mul' || opKey === 'div')
        && chosen % 10 === correct % 10) {
        return 'ошибка в десятках';
    }

    // Не сошлась ни одна цифра. Это третий угол квадрата ловушек, который
    // строит генератор для сложения и вычитания (см. addSubDecoyPlan): два
    // других его угла разбираются правилами выше, а этот до сих пор уходил
    // в «другую ошибку» — и составлял её большую часть.
    //
    // Оба числа должны быть не меньше десяти: у однозначных десятков нет,
    // и говорить про них «оба разряда» бессмысленно.
    if (sameSide && (opKey === 'add' || opKey === 'sub')
        && chosen >= 10 && correct >= 10
        && Math.floor(chosen / 10) !== Math.floor(correct / 10)) {
        return 'оба разряда мимо';
    }

    // Ответ рядом, но не соседний. На однозначных ответах генератор ставит
    // именно такие варианты — «считал, но сбился», — и до сих пор половина
    // разбора первой звезды вычитания уходила в «другую ошибку». Ставится
    // последним: любая названная причина полезнее общего «мимо».
    if (sameSide && (opKey === 'add' || opKey === 'sub')
        && Math.abs(chosen - correct) <= 5) {
        return 'промахнулся рядом';
    }

    // Ответ ушёл не в ту сторону от нуля, и само число тоже другое — не зеркало
    // верного, иначе это было бы «ошибся в знаке» выше. Все правила про разряды
    // сюда уже не дошли: они смотрят только на одну сторону. Раньше этот случай
    // падал в «другую ошибку» и составлял три четверти её на отрицательных.
    //
    // Причину числа мы не знаем и не называем. Называем то, что знаем точно:
    // знак не тот. Подсказка поэтому даёт правило знака и просит пересчитать.
    if (isNegative && chosen !== 0 && correct !== 0
        && Math.sign(chosen) !== Math.sign(correct)) {
        return 'знак и число мимо';
    }
    return null;
}

// Ноль в примере — отдельная беда, и до сих пор она рассыпалась по трём чужим
// видам: «другая ошибка», «сложил вместо умножения», «мимо на единицу».
// Последнее особенно скверно: ребёнок, выбравший 1 вместо 0×8, не торопится —
// он не знает правила, а ему советовали «считать на полсекунды дольше».
//
// Деление ноля сюда же: 0 ÷ 10 путают с 10 ÷ 0 постоянно, и «Нет решения»
// в качестве ответа — это ровно та же путаница, поэтому строковый выбор
// здесь тоже считается ошибкой этого вида.
function classifyZeroInExample(opKey, problem, chosen) {
    const a = problem && problem.a, b = problem && problem.b;
    if (typeof a !== 'number' || typeof b !== 'number') return null;
    if (chosen === 0) return null;              // ноль и выбрал — это не эта ошибка
    if (opKey === 'mul' && (a === 0 || b === 0)) return 'ноль в примере';
    if (opKey === 'div' && a === 0 && b !== 0) return 'ноль в примере';
    return null;
}

// «Дробь от числа»: модели ошибок здесь свои, см. buildFracOfNumberDistractors.
// «В смешанное» и «В неправильную». Варианты ответа построены как конкретные ошибки
// (buildMixedConvertDistractors), и разбор узнаёт их по величине выбранной дроби.
// Названия утвердил репетитор 04.11. Вариант, не похожий ни на одну из этих ошибок,
// остаётся «ошибкой при переводе» — как было для всех до этой правки.
function classifyMixedConvert(problem, correct, chosen) {
    if (!isFrac(chosen) || !isFrac(correct)) return null;
    const { whole, properNum, den, direction } = problem;
    if (!(whole >= 1) || !(properNum >= 1) || !(den >= 2)) return null;
    const is = (num) => chosen.num * den === num * chosen.den;
    if (direction === 'toMixed') {
        if (is(properNum)) return 'забыл целую часть';
        // Перестановку видно, только когда переставленная запись — смешанное число с
        // правильной дробью: у 3 1/2 она дала бы «1 3/2», а на экране это 2 1/2.
        if (whole < den && whole !== properNum && is(properNum * den + whole)) return 'переставил целую и остаток';
        if (is((whole - 1) * den + properNum) || is((whole + 1) * den + properNum)) return 'ошибся в целой части';
        return null;
    }
    if (is(whole * den)) return 'не прибавил числитель';
    if (is(whole + properNum)) return 'сложил целую и числитель';
    if (is(correct.num + den) || is(correct.num - den)) return 'ошибся в целой части';
    return null;
}

function classifyFracOfNumber(problem, correct, chosen) {
    if (typeof chosen !== 'number') return null;
    const { fracNum, N, k } = problem;
    if (chosen === N * fracNum) return 'забыл поделить';
    if (chosen === k && k !== correct) return 'нашёл только одну долю';
    if (chosen === N - correct) return 'нашёл остаток';
    if (k && (chosen === correct + k || chosen === correct - k)) return 'ошибся на одну долю';
    if (Math.abs(chosen - correct) === 1) return 'ошибся на единицу';
    return null;
}

// Главная точка входа. meta — то же, что в currentProblemMeta.
function classifyMistake(meta, problem, correct, chosen) {
    if (!meta || !problem) return 'другая ошибка';
    const opKey = meta.opKey;

    // Выбрали число там, где верный ответ — «нет решения» (деление на ноль).
    if (problem.noSolution && chosen !== 'NO_SOLUTION') return 'делил на ноль';


    try {
        if (meta.category === 'fraction') {
            if (opKey === 'simplify') {
                if (!isFrac(chosen)) return 'другая ошибка';
                // Величина та же, запись другая — значит сократил, но не до упора.
                if (sameValue(chosen, correct)) return 'сократил не до конца';
                return 'ошибся в сокращении';
            }
            if (opKey === 'toMixed' || opKey === 'toImproper') {
                return classifyMixedConvert(problem, correct, chosen) || 'ошибся в переводе';
            }
            if (opKey === 'fracOfNumber') return classifyFracOfNumber(problem, correct, chosen) || 'другая ошибка';
            return classifyFractionArith(problem, correct, chosen) || 'другая ошибка';
        }

        if (meta.category === 'decimal') {
            if (!isDecimalValue(chosen) || !isDecimalValue(correct)) return 'другая ошибка';
            const d1 = problem.d1, d2 = problem.d2;
            const val = (d) => d.intVal / Math.pow(10, d.dp);
            const cv = val(correct), gv = val(chosen);

            if (gv === -cv && cv !== 0) return 'ошибся в знаке';

            // Те же цифры, но запятая сдвинута — самая частая беда десятичных.
            if (chosen.intVal === correct.intVal && chosen.dp !== correct.dp) return 'запятая не на месте';

            if (d1 && d2) {
                const commonDp = Math.max(d1.dp, d2.dp);
                const v1 = d1.intVal * Math.pow(10, commonDp - d1.dp);
                const v2 = d2.intVal * Math.pow(10, commonDp - d2.dp);
                // Сравниваем без нулей в конце: варианты ответа приходят уже без них
                // (0,40 показывается как 0,4), а посчитанная здесь ошибка — нет. Раньше
                // «0,75 − 0,35 → 1,10» не узнавалось как «не то действие» и уходило
                // в «другую ошибку»: 1,1 ≠ 1,10 по записи.
                const plain = stripTrailingZeros(chosen);
                const same = (iv, dp) => {
                    const x = stripTrailingZeros({ intVal: iv, dp });
                    return plain.intVal === x.intVal && plain.dp === x.dp;
                };

                // Сложил сырые цифры, не выровняв запятые (0.5 + 0.25 как 5 + 25).
                if ((opKey === 'add' || opKey === 'sub') && d1.dp !== d2.dp) {
                    const raw = opKey === 'add' ? d1.intVal + d2.intVal : d1.intVal - d2.intVal;
                    if (same(raw, Math.max(d1.dp, d2.dp))) return 'не выровнял запятую';
                }
                // Ошибка в столбик: сложили без переноса (2,7 + 1,5 = 3,2) или вычли
                // наоборот (5,2 − 3,8 = 2,6). Модель та же, что строит вариант ответа.
                const column = decColumnMistake(opKey, d1, d2);
                if (column && same(column.intVal, column.dp)) return opKey === 'add' ? 'не перенёс единицу' : 'переставил цифры';
                // Соседний факт таблицы в умножении и делении (вариант Б, 04.11).
                if (decTableSlips(opKey, d1, d2).some(v => same(v.intVal, v.dp))) return 'таблица умножения';
                if (opKey === 'add' && same(v1 - v2, commonDp)) return 'перепутал действие';
                if (opKey === 'sub' && same(v1 + v2, commonDp)) return 'перепутал действие';
                if (opKey === 'mul') {
                    if (same(v1 + v2, commonDp)) return 'сложил вместо умножения';
                    const raw = d1.intVal * d2.intVal;
                    if (chosen.intVal === raw && chosen.dp !== d1.dp + d2.dp) return 'запятая не на месте';
                }
                if (opKey === 'div' && same(d1.intVal * d2.intVal, d1.dp + d2.dp)) return 'перепутал действие';
            }

            if (gv !== 0 && cv !== 0) {
                const ratio = gv / cv;
                for (const k of [0.001, 0.01, 0.1, 10, 100, 1000]) {
                    if (Math.abs(ratio - k) < 1e-9) return 'запятая не на месте';
                }
            }
            // Вариант Б: ответ рядом — на той же сетке знаков, что и верный, — промах в
            // счёте, а не «другая ошибка». Граница та же, что у случайного варианта.
            // Сравнение по величине: у 9,0 ноль в конце убран, и запись короче, чем у 9,7.
            if (chosen.dp <= correct.dp) {
                const diff = Math.abs(chosen.intVal * Math.pow(10, correct.dp - chosen.dp) - correct.intVal);
                if (diff >= 1 && diff <= Math.max(3, Math.round(Math.abs(correct.intVal) * 0.2))) return 'промахнулся рядом';
            }
            return 'другая ошибка';
        }

        const zero = classifyZeroInExample(opKey, problem, chosen);
        if (zero) return zero;

        // Обратная путаница: решение есть, а выбрано «нет решения». Вариант
        // этот стоит на экране намеренно (см. buildDistractors) и означает ту же
        // нетвёрдость в правиле, только с другой стороны: запрещено делить НА
        // ноль, а не делить ноль и не делить вообще.
        //
        // Отдельным видом, а не общим с «делил на ноль»: репетитору важно, в
        // какую сторону ученик путает — не применил правило или применил не к
        // месту. До сих пор этот выбор уходил в «другую ошибку», потому что
        // разбор целых чисел берёт только числа, а здесь ответ строковый.
        //
        // СТРОГО ПОСЛЕ разбора нуля. У примера «0 ÷ 10» выбор «нет решения» —
        // это уже названная ошибка «ноль в примере»: путаница между делением
        // ноля и делением на ноль. Стой эта проверка выше, она перехватывала бы
        // её и подменяла более точное имя менее точным.
        if (chosen === 'NO_SOLUTION' && !meta.isNegative) return 'нет решения зря';

        return classifyIntegerLike(problem, correct, chosen, opKey, !!meta.isNegative)
               || 'другая ошибка';
    } catch (e) {
        // Разбор ошибок не имеет права уронить игру: не разобрались — и ладно.
        return 'другая ошибка';
    }
}

// ===================== ПОДСКАЗКИ ПО ОШИБКАМ =====================
// Тексты лежат в content/hints.js. Здесь — когда показывать и какие числа
// подставить: подсказка говорит числами того примера, на котором ученик
// споткнулся, иначе она превращается в общее место вроде «бывает перенос».
//
// Показываем скупо. Ошибка одного вида должна повториться трижды за миссию —
// один промах это случайность, а не пробел. Один вид подсказывается один раз,
// всего за миссию не больше двух подсказок: третья это уже урок посреди игры.
const HINT_REPEAT_AT = 3;
const HINT_MAX_PER_SESSION = 2;
// «Другая ошибка» — корзина, про которую мы честно ничего не знаем; «не сократил»
// это вообще не ошибка в счёте. Молчать здесь лучше, чем говорить наугад.
const HINT_NEVER = ['другая ошибка', 'не сократил'];

function resolveHints() {
    const all = (typeof window !== 'undefined' && window.HINT_CONTENT) || null;
    if (!all) return null;
    const lang = (typeof LANG === 'string' && LANG) || 'ru';
    return all[lang] || all.ru || null;
}

// Ключ ищем сначала с вариантом ('ошибся в знаке:addDiff'), потом с действием
// ('ошибка в десятках:add'), потом без них: у сложения и вычитания одна и та же
// ошибка объясняется разными словами, а у знака — ещё и разными правилами.
function hintEntry(kind, opKey, variant) {
    const table = resolveHints();
    if (!table || !kind) return null;
    return (variant && table[kind + ':' + variant])
        || (opKey && table[kind + ':' + opKey]) || table[kind] || null;
}

// Отрицательная ли арифметика в этом примере. Смотрим на сами числа, а не на
// meta.isNegative: в разбор после миссии meta приходит без этого флага.
function hintNegArith(problem, correct) {
    const a = problem && problem.a, b = problem && problem.b;
    return a < 0 || b < 0 || (typeof correct === 'number' && correct < 0);
}

// Какой из текстов вида взять. Правило знака у сложения и у умножения разное,
// а внутри каждого — своё для одинаковых и для разных знаков. Одной фразой на
// все случаи оно не скажется без вранья: «знак у большего числа» неверно уже на
// −8 + 7, ведь −8 меньше семи.
//
// Для сложения и вычитания берём те же два числа, что и приём до ответа
// (neg:same / neg:diff): первое число и то, что к нему на деле прибавили.
// У «3 − 8» это 3 и −8. Так правило после ошибки звучит теми же словами и о
// тех же числах, что и подсказка до неё.
function hintVariant(kind, meta, problem, correct, chosen) {
    if (isDecProblem(problem)) return decHintVariant(kind, meta, problem, correct, chosen);
    const op = meta && meta.opKey;
    const a = problem && problem.a, b = problem && problem.b;
    if (typeof a !== 'number' || typeof b !== 'number') return null;

    if (kind === 'ошибся в знаке' || kind === 'знак и число мимо') {
        if (op === 'add' || op === 'sub') {
            if (typeof correct !== 'number') return null;
            const x = a, y = correct - a;
            if (x === 0 || y === 0) return null;
            return Math.sign(x) === Math.sign(y) ? 'addSame' : 'addDiff';
        }
        if (op === 'mul' || op === 'div') {
            // Три множителя на экране — «два одинаковых знака» тут неправда.
            if (problem.triple) return 'mulTriple';
            if (a === 0 || b === 0) return null;
            return (a < 0) === (b < 0) ? 'mulSame' : 'mulDiff';
        }
        return null;
    }

    // «Спутал модули»: правило одно, а слова — по делу (знаки одинаковые или
    // разные) и по записи. Если между числами на экране минус («3 − 8», «−7 − 3»),
    // первым шагом вычитание переписывают в сумму: «3 − 8 — это 3 + (−8)».
    if (kind === 'спутал модули' && (op === 'add' || op === 'sub')) {
        if (typeof correct !== 'number') return null;
        const x = a, y = correct - a;
        if (x === 0 || y === 0) return null;
        return (Math.sign(x) === Math.sign(y) ? 'same' : 'diff') + (negShownMinus(op, b) ? 'Minus' : 'Plus');
    }

    // Десятки на отрицательном сложении. Столбик тут идёт не по записи, а по
    // тому, что делают с числами на деле: при одинаковых знаках их складывают,
    // при разных — из дальнего вычитают ближнее. «−17 − 18» — это сложение
    // 17 и 18, и рассказ про «десяток, который занимали» был бы враньём.
    if (kind === 'ошибка в десятках' && (op === 'add' || op === 'sub')
        && hintNegArith(problem, correct) && typeof correct === 'number') {
        const x = a, y = correct - a;
        if (x === 0 || y === 0) return null;
        return Math.sign(x) === Math.sign(y) ? 'add' : 'sub';
    }
    return null;
}

// Отрицательное число после знака действия пишется в скобках: «4 × (−5)».
// Так оно выглядит в самом примере, и подсказка не должна писать иначе.
function hintParen(n) {
    return (typeof n === 'number' && n < 0) ? '(' + showMinus(n) + ')' : String(n);
}

// Отрицательные сложение и вычитание без скобок: какой знак стоит между числами
// на экране. Запись строит formatAddSubText: минус второго числа переворачивает
// знак действия («5 + (−3)» показывается как «5 − 3»), поэтому минус на экране —
// это вычитание положительного или сложение отрицательного.
function negShownMinus(op, b) {
    return (op === 'sub') === (b >= 0);
}
// Сама запись — ровно та, что была на экране, с настоящим минусом.
function negAddSubShown(op, a, b, withParen) {
    if (typeof formatAddSubText !== 'function') return '';
    return showMinus(formatAddSubText(a, op === 'sub' ? '-' : '+', b, !!withParen));
}

// Какую клетку таблицы ученик посчитал на самом деле. Вид ошибки ставится
// ровно тогда, когда неверный ответ равен соседней клетке, — значит её можно
// назвать прямо, а не отделываться словом «соседняя».
function mulFactUsed(a, b, chosen) {
    const cands = [[a, b + 1], [a, b - 1], [a + 1, b], [a - 1, b]];
    for (const pair of cands) if (pair[0] * pair[1] === chosen) return pair;
    return null;
}

// Аргументы подстановки, отдельно для строки в игре и для разбора. Порядок
// описан в шапке content/hints.js и обязан совпадать во всех языках.
function hintArgs(kind, meta, problem, correct, chosen) {
    if (isDecProblem(problem)) return decHintArgs(kind, meta, problem, correct, chosen);
    const op = meta && meta.opKey;
    const a = problem && problem.a, b = problem && problem.b;
    if (typeof a !== 'number' || typeof b !== 'number') return null;
    const u = (x) => Math.abs(x) % 10;

    // Знак. Раскладка одна на все тексты этих двух видов: первым идёт число со
    // знаком, у которого ответ этот знак берёт, дальше — сами числа без знаков,
    // как их и считают. Для умножения чисел не нужно: правило говорит само.
    if (kind === 'ошибся в знаке' || kind === 'знак и число мимо') {
        const variant = hintVariant(kind, meta, problem, correct);
        if (!variant) return null;
        if (variant === 'addSame' || variant === 'addDiff') {
            const x = a, y = correct - a;
            if (Math.abs(x) === Math.abs(y)) return null;  // ответ ноль — знака у него нет
            const far = Math.abs(x) > Math.abs(y) ? x : y;
            const near = far === x ? y : x;
            // При одинаковых знаках знак ответа — это знак любого из двух чисел;
            // называем первое, как и приём до ответа.
            const ref = variant === 'addSame' ? x : far;
            const first = variant === 'addSame' ? Math.abs(x) : Math.abs(far);
            const second = variant === 'addSame' ? Math.abs(y) : Math.abs(near);
            return { game: [ref], review: [ref, first, second] };
        }
        return { game: [], review: [] };
    }

    // Модули: для diff — больший и меньший, для same — первый и второй, как их и
    // считают. Дальше запись примера и она же суммой: «3 − 8» и «3 + (−8)».
    if (kind === 'спутал модули') {
        if ((op !== 'add' && op !== 'sub') || typeof correct !== 'number') return null;
        const x = a, y = correct - a;
        if (x === 0 || y === 0) return null;
        const shown = negAddSubShown(op, a, b, false);
        if (!shown) return null;
        const asSum = `${showMinus(a)} + ${hintParen(y)}`;
        if (Math.sign(x) === Math.sign(y)) {
            const args = [Math.abs(x), Math.abs(y), shown, asSum];
            return { game: args, review: args };
        }
        // Ответ ноль — знака у него нет, и «знак — как у числа с бо́льшим модулем»
        // было бы неправдой. Молчим.
        if (Math.abs(x) === Math.abs(y)) return null;
        const args = [Math.max(Math.abs(x), Math.abs(y)), Math.min(Math.abs(x), Math.abs(y)), shown, asSum];
        return { game: args, review: args };
    }

    // Скобки бывают только у отрицательного второго числа; «двойной минус» —
    // у вычитания, «минус в скобках» — у сложения. Запись со скобками и она же
    // без них: «5 − (−3)» — «5 + 3», «5 + (−3)» — «5 − 3». Дальше считает ученик.
    if (kind === 'двойной минус' || kind === 'минус в скобках') {
        if (b >= 0 || op !== (kind === 'двойной минус' ? 'sub' : 'add')) return null;
        const shown = negAddSubShown(op, a, b, true);
        if (!shown) return null;
        const open = showMinus(`${a} ${op === 'sub' ? '+' : '-'} ${Math.abs(b)}`);
        return { game: [shown, open], review: [shown, open] };
    }

    if (kind === 'ошибка в десятках') {
        // Про перенос и заём говорим, только если они в этом примере есть.
        // «10 + 7 = 17, выбрал 27» — единицы 0 + 7, наверх ничего не уходит,
        // и объяснять промах потерянным переносом значит врать. Молчим.
        //
        // На отрицательных столбик считают по тому, что делают с числами на деле
        // (см. hintVariant): при одинаковых знаках складывают, при разных — из
        // дальнего от нуля вычитают ближнее. Подставляем эти самые числа, без
        // знаков — так, как их и считают. Текст берётся тоже по делу, а не по
        // записи: у «−17 − 18» это текст про сложение.
        if ((op === 'add' || op === 'sub') && hintNegArith(problem, correct)) {
            if (typeof correct !== 'number') return null;
            const x = a, y = correct - a;
            if (x === 0 || y === 0) return null;
            if (Math.sign(x) === Math.sign(y)) {
                const su = u(x) + u(y);
                if (su < 10) return null;
                return { game: [], review: [Math.abs(x), Math.abs(y), u(x), u(y), su, su % 10] };
            }
            const far = Math.max(Math.abs(x), Math.abs(y));
            const near = Math.min(Math.abs(x), Math.abs(y));
            if (u(far) >= u(near)) return null;  // заёма нет — заём и не при чём
            return { game: [], review: [far, near] };
        }
        if (op === 'add') {
            const su = u(a) + u(b);
            if (su < 10) return null;
            return { game: [], review: [a, b, u(a), u(b), su, su % 10] };
        }
        if (op === 'sub') {
            if (u(a) >= u(b)) return null;  // заёма нет — заём и не при чём
            return { game: [], review: [a, b] };
        }
        // Умножение и деление. Вид сюда попадает по совпадению последней цифры,
        // поэтому промах всегда кратен десяти — но говорить о переносе и заёме,
        // как в сложении, здесь нельзя: их тут нет. Слова другие.
        if (typeof correct !== 'number' || typeof chosen !== 'number') return null;
        if (op === 'div') {
            // Деление проверяется умножением, и неверный ответ проверку не проходит.
            // Про «ровно на десяток» говорим, только если промах и правда десяток:
            // сейчас он такой всегда, но генератор нам ничего не обещал.
            if (b === 0 || Math.abs(chosen - correct) !== 10) return null;
            // b везде стоит после знака действия, поэтому пишется в скобках,
            // если он отрицательный. У положительных ничего не меняется.
            return { game: [chosen, hintParen(b), chosen * b, a],
                     review: [a, hintParen(b), correct, chosen, chosen * b] };
        }
        if (op === 'mul') {
            // Три множителя: в шаблоне стоит «%2 × %3», и мы кладём туда запись
            // целиком — первые два множителя в %2, третий в %3. Выходит ровно
            // «−5 × 7 × 5», как на экране, а не «−35 × 5». Шаблоны при этом те же
            // во всех четырёх языках. Нет множителей — молчим: лучше ничего, чем
            // пример, которого ребёнок не видел.
            if (problem.triple) {
                const f = problem.factors;
                if (!Array.isArray(f) || f.length !== 3) return null;
                const head = showMinus(f[0]) + ' × ' + hintParen(f[1]), tail = hintParen(f[2]);
                return { game: [Math.abs(chosen - correct), head, tail],
                         review: [head, tail, correct, chosen] };
            }
            return { game: [Math.abs(chosen - correct), a, hintParen(b)],
                     review: [a, hintParen(b), correct, chosen] };
        }
        return null;
    }
    if (kind === 'ошибка в единицах') {
        // Столбик должен существовать. Если оба числа однозначные, единицы —
        // это и есть весь пример, и «посчитай отдельно 9 + 1» просто повторяет
        // условие. Это четверть всех срабатываний вида.
        if (Math.max(a, b) < 10) return null;
        if (op === 'add') { const su = u(a) + u(b); return { game: [u(a), u(b)], review: [a, b, u(a), u(b), su, su % 10] }; }
        if (typeof correct !== 'number') return null;
        return { game: [], review: [a, b, u(correct)] };
    }
    if (kind === 'не занял десяток') {
        return { game: [u(a), u(b), u(a) + 10],
                 review: [a, b, u(a), u(b), u(a) + 10, u(a) + 10 - u(b)] };
    }
    if (kind === 'таблица умножения') {
        const pair = mulFactUsed(a, b, chosen);
        if (!pair || typeof correct !== 'number') return null;
        // Клетка с нулём — формально соседняя, а сказать про неё нечего.
        if (pair[0] === 0 || pair[1] === 0) return null;
        return { game: [pair[0], pair[1], a, b, Math.abs(correct - chosen)],
                 review: [pair[0], pair[1], chosen, a, b, correct] };
    }
    if (kind === 'сложил вместо умножения') {
        // «1 × 6 — это 6 раза по 1» ничему не учит и звучит криво.
        if (a === 1 || b === 1) return null;
        const times = hintCountPhrase('times', b);
        return { game: [a, b, times], review: [a, b, correct, a + b, times] };
    }
    if (kind === 'перепутал действие') {
        return { game: [], review: [a, b, correct, chosen] };
    }
    if (kind === 'взял одно из чисел') {
        // При делителе 1 ответ равен делимому, и фраза «ответ всегда меньше
        // делимого» в разборе становится неправдой.
        if (b === 1) return null;
        return { game: [a, b], review: [a, b, correct] };
    }
    if (kind === 'ноль в примере') {
        if (op === 'div') return { game: [], review: [a, b] };
        // В умножении считаем нулями по второму множителю: «сложи восемь нулей».
        // Если оба нуля — считать нечего, молчим.
        if (a === 0 && b === 0) return null;
        return { game: [hintCountPhrase('zeros', a === 0 ? b : a)], review: [a, b] };
    }
    if (kind === 'делил на ноль') {
        return { game: [], review: [a] };
    }
    if (kind === 'ошибся на единицу') {
        // В делении вместо разговора о спешке показываем саму проверку: верный
        // ответ на делитель даёт делимое, а выбранный — нет. Это самая частая
        // клетка для этого вида, и проверка тут нагляднее любых уговоров.
        if (op === 'div') {
            if (b === 0 || typeof correct !== 'number' || typeof chosen !== 'number') return null;
            const args = [correct, b, a, chosen, chosen * b];
            return { game: args, review: args };
        }
        return { game: [], review: [chosen, correct] };
    }
    if (kind === 'промахнулся рядом') {
        return { game: [], review: [chosen, correct] };
    }
    if (kind === 'оба разряда мимо') {
        if (typeof correct !== 'number' || typeof chosen !== 'number') return null;
        return { game: [], review: [chosen, correct, u(correct), Math.floor(correct / 10)] };
    }
    if (kind === 'не умножил десятки') {
        const lo = Math.min(a, b), hi = Math.max(a, b);
        // Те же условия, что и у самого вида: без них подстановки соврут.
        if (hi < 11 || hi % 10 === 0 || lo <= 1 || typeof correct !== 'number') return null;
        const tens = Math.floor(hi / 10) * 10;
        return { game: [lo, u(hi)],
                 review: [lo, u(hi), lo * u(hi), tens, lo * tens, correct] };
    }
    if (kind === 'нет решения зря') {
        if (b === 0 || typeof correct !== 'number') return null;
        return { game: [b], review: [a, b, correct] };
    }
    return null;
}

