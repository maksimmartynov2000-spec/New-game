// Заморозка. Часы миссии и полоска времени крутятся по одному флагу gameActive —
// снять его достаточно, чтобы всё встало. Ученику это видно: полоска покрывается
// инеем, поверх стоит надпись «время остановлено». Спешить незачем, поэтому
// автоскрытия нет: подсказка ждёт нажатия.
let hintFreezeResume = null;

function showHintFreeze(text, onDone, extra) {
    const done = typeof onDone === 'function' ? onDone : function () {};
    const box = document.getElementById('hintFreeze');
    if (!box || !text) { done(); return; }
    try {
        const put = (id, value) => {
            const el = document.getElementById(id);
            if (!el) return;
            el.innerText = value || '';
            el.hidden = !value;
        };
        put('hintFreezeExample', extra && extra.example);
        put('hintFreezeChosen', extra && extra.chosen);
        document.getElementById('hintFreezeText').innerText = text;
        document.getElementById('hintFreezeLabel').innerText = t('Время остановлено');
        document.getElementById('hintFreezeTap').innerText = t('Нажми, чтобы продолжить');
        const bar = document.getElementById('timerBar');
        if (bar) bar.classList.add('frozen');
        gameActive = false;
        box.hidden = false;
        hintFreezeResume = () => {
            hintFreezeResume = null;
            box.hidden = true;
            if (bar) bar.classList.remove('frozen');
            gameActive = true;
            done();
        };
        box.onclick = () => { if (hintFreezeResume) hintFreezeResume(); };
    } catch (e) {
        // Подсказка — надстройка. Что бы с ней ни случилось, игра обязана идти.
        box.hidden = true;
        gameActive = true;
        done();
    }
}

// ===================== ПРИЁМЫ: ПОДСКАЗКА ДО ОТВЕТА =====================
// Всё выше отвечает на вопрос «что ты сделал не так». Здесь — на вопрос «как это
// считать», и отвечает ДО ответа. Работает только в режиме обучения.
//
// Группы берутся у structuralClassOf — того же кода, которым считается разбор в
// статистике. Своей классификации тут нет: разойдись они, и подсказка начала бы
// объяснять не тот приём, по которому ученика потом посчитают.
function resolveTricks() {
    const all = (typeof window !== 'undefined' && window.TRICK_CONTENT) || null;
    if (!all) return null;
    const lang = (typeof LANG === 'string' && LANG) || 'ru';
    return all[lang] || all.ru || null;
}

// Какой приём показать и с какими числами. Возвращает { key, args } либо null,
// если приёма у этого примера нет — «без перехода», «без заёма», ×1 и ×0.
//
// Вторая ось важнее основного класса. 68 + 57 — это и «полный переход», и «через
// сотню»; обе подсказки верны, но первая доведёт только до семидесяти, а трудность
// здесь — сотня. Строка одна, и достаётся она более трудному.
function trickPick(meta, problem) {
    if (!meta || !problem) return null;
    const struct = (typeof structuralClassOf === 'function')
        ? structuralClassOf(meta, problem) : null;
    if (!struct) return null;
    const a = problem.a, b = problem.b;
    if (typeof a !== 'number' || typeof b !== 'number') return null;
    const op = meta.opKey;
    const u = (n) => Math.abs(n) % 10;

    // ===== ОТРИЦАТЕЛЬНЫЕ =====
    //
    // До этой правки режим обучения на отрицательных МОЛЧАЛ: замер по генератору дал
    // 0% подсказок у сложения и вычитания на всех пяти звёздах и 3–5% у умножения.
    // Причина простая: приёмы ниже разбирают класс примера ('1', '2', 'h'), а у
    // отрицательных классы совсем другие — 'same', 'near', 'cross' — и ни одна ветка
    // не срабатывала. Деление сюда не входит: общий приём «на что умножить» работает
    // с отрицательными как есть и учит именно знаку (90–99% покрытия).
    //
    // Приёмы здесь — школьные правила знаков, и каждый останавливается за шаг до
    // ответа: последний счёт ученик делает сам.
    if (meta.isNegative) {
        if (op === 'add' || op === 'sub') {
            // Приводим к виду «x + y» — ровно так же, как это делает structuralClassOf:
            // второе слагаемое достаём из ответа, чтобы разбор не зависел от того,
            // перевернул ли генератор знак при показе.
            const ans = problem.answer;
            if (typeof ans !== 'number') return null;
            const x = a, y = ans - a;
            if (x === 0 || y === 0) return null;   // ноль — не правило знаков
            if (Math.sign(x) === Math.sign(y)) {
                // Знак не называем словом: он и так виден в примере, а назвать его
                // значит подсказать половину ответа там, где вся задача — про знак.
                return { key: 'neg:same', args: [Math.abs(x), Math.abs(y)] };
            }
            const бол = Math.abs(x) >= Math.abs(y) ? x : y;
            const мен = Math.abs(x) >= Math.abs(y) ? y : x;
            // Модули равны — числа гасят друг друга в ноль. Вычитать нечего, и
            // «из 7 вычти 7» было бы не приёмом, а самим ответом.
            if (Math.abs(бол) === Math.abs(мен)) return null;
            return { key: 'neg:diff', args: [Math.abs(бол), Math.abs(мен), бол] };
        }
        if (op === 'mul') {
            // Три множителя: правило то же, что у пары, только считать приходится
            // минусы, а не сравнивать два знака. Число минусов называем словом —
            // сосчитать их и есть весь приём, — а сами множители отдаём без знаков,
            // в том порядке, в каком они стоят в примере. Перемножает ученик сам.
            // До этой правки здесь было молчание: 35% примеров пятой звезды.
            if (problem.triple) {
                const f = problem.factors;
                if (!Array.isArray(f) || f.length !== 3) return null;
                const minuses = f.filter(v => v < 0).length;
                return { key: 'neg:triple' + minuses, args: f.map(v => Math.abs(v)) };
            }
            // ×1 и ×0 пропускаем по той же причине, что и у положительных: это не
            // приём, а определение, и правило знаков там выдало бы готовый ответ.
            if (struct.cls === 'triv') return null;
            const одинаковые = (a < 0) === (b < 0);
            return { key: одинаковые ? 'neg:mulSame' : 'neg:mulDiff',
                     args: [Math.abs(a), Math.abs(b)] };
        }
        // Деление падает ниже, в общий приём.
    }

    if (op === 'add') {
        // Достраиваем до круглого БОЛЬШЕЕ число, а не первое. У 25 + 80 от двадцати
        // пяти до сотни не хватает 75 — и ученику пришлось бы считать 80 − 75, что
        // тяжелее самого примера. От восьмидесяти не хватает 20, и это уже приём.
        const big = Math.max(a, b), small = Math.min(a, b);
        if (struct.extra === 'h') {
            const hundred = (Math.floor(big / 100) + 1) * 100;
            const need = hundred - big;
            // Добирать нужно из второго числа — если его не хватает, приём не работает.
            if (need > 0 && need < small) return { key: 'add:h', args: [hundred, need, small] };
        }
        if (struct.cls === '1') return { key: 'add:1', args: [u(a), u(b)] };
        if (struct.cls === '2') {
            const round = (Math.floor(big / 10) + 1) * 10;
            const need = round - big;
            if (need > 0 && need < small) return { key: 'add:2', args: [round, need, small] };
        }
        return null;                      // «без перехода» — приёма нет
    }

    if (op === 'sub') {
        if (struct.extra === 'h') {
            const tail = a % 100;
            const hundred = a - tail;
            // Спуск до сотни работает, только если хвост есть и его хватает вычесть.
            if (tail > 0 && tail < b) {
                // Та же защита, что у спуска к десятку: остаток «потом ещё X» иногда
                // САМ РАВЕН ОТВЕТУ (101 − 51 = 50, и остаток тоже 50). Ребёнку, который
                // просто читает последнее число, считать уже нечего. Редко — 0,13% всех
                // подсказок вычитания, и только на 5★ — но чинится тем же переворотом
                // в сложение, без единого молчания.
                if (b - tail !== a - b) return { key: 'sub:h', args: [tail, hundred, b - tail] };
                return { key: 'sub:toAdd', args: [b, a] };
            }
        }
        if (struct.cls === '1' || struct.cls === '2') {
            const top = u(a) + 10, low = u(b);
            // Шаг «займи десяток» ИНОГДА СОВПАДАЕТ СО ВСЕМ ПРИМЕРОМ — и тогда подсказка
            // печатает ученику готовый ответ. У 23 − 7 шаг это 13 − 7 = 6, а ответ 16:
            // всё честно. У 12 − 4 шаг это 12 − 4 = 8, то есть сам пример и сам ответ.
            //
            // Сравниваем прямо: шаг и ответ. Можно было написать «десятки первого на
            // один больше десятков второго» — это равносильно, проверено перебором всех
            // 8730 пар с заёмом до 200. Но прямое сравнение говорит ровно то, что нас
            // волнует, работает с любыми знаками и не разъедется, если однажды
            // поменяется сам приём.
            //
            // Замер до этой правки, по настоящему генератору: на 1★ ответ печатался в
            // 100% подсказок вычитания, на 2★ в 94,6%. Нашёл это не тест, а Максим на
            // уроке с учеником.
            if (top - low === a - b) {
                const tail = a % 10;      // хвост до круглого
                const rest = b - tail;    // сколько останется отнять после спуска
                // Спуск до круглого — приём получше переворота, но годится не всегда:
                //   tail > 0        у 10 − 6 спускаться некуда, число уже круглое;
                //   rest < 10       у 64 − 57 остаток вышел бы 53, а «отнять 53 от 60»
                //                   тяжелее самого примера;
                //   rest !== a - b  у 14 − 9 остаток 5 и ответ 5 — спуск сам начал бы течь.
                if (tail > 0 && rest > 0 && rest < 10 && rest !== a - b) {
                    return { key: 'sub:ten', args: [tail, a - tail, rest] };
                }
                // Переворот в сложение. Печатаются только два числа самого примера,
                // поэтому новой информации не выдаётся в принципе: утечка невозможна
                // по устройству, а не по удаче. Ровно так же устроена подсказка деления.
                return { key: 'sub:toAdd', args: [b, a] };
            }
            return { key: 'sub:borrow', args: [top, low, top - low] };
        }
        return null;                      // «без заёма» — приёма нет
    }

    if (op === 'mul') {
        if (a < 0 || b < 0 || problem.triple) return null;
        const lo = Math.min(a, b), hi = Math.max(a, b);
        switch (struct.cls) {
            case 'triv':
                // Приём есть только у десятки. ×1 и ×0 — не приём, а определение.
                return (hi === 10 && lo > 0) ? { key: 'mul:triv10', args: [] } : null;
            case 'two':  return { key: 'mul:two', args: [hi] };
            case 'five': {
                const other = (b === 5) ? a : b;
                return { key: 'mul:five', args: [other * 10] };
            }
            case 'small': {
                const other = hi;
                return (lo === 4)
                    ? { key: 'mul:small4', args: [other * 2] }
                    : { key: 'mul:small3', args: [other * 2] };
            }
            case 'nine': {
                const other = (b === 9) ? a : b;
                return { key: 'mul:nine', args: [other, other * 10, other] };
            }
            case 'core': {
                // Порядок выбора: шестёрка, потом восьмёрка, потом семёрка. Так
                // каждому факту достаётся самый короткий путь — 7 × 8 это 70 − 14,
                // а не 80 − 24.
                if (a === 6 || b === 6) {
                    const other = (b === 6) ? a : b;
                    return { key: 'mul:core6', args: [other, other * 3] };
                }
                if (a === 8 || b === 8) {
                    const other = (b === 8) ? a : b;
                    return { key: 'mul:core8', args: [other, other * 10, other * 2] };
                }
                const other = a;                     // остаётся только 7 × 7
                return { key: 'mul:core7', args: [other, other * 10, other * 3] };
            }
            // Двузначные. У «круглых» круглый множитель есть всегда (проверено
            // прогоном генератора), поэтому приём «убери ноль» безопасен; у двузначных
            // без нуля второй множитель всегда однозначный, и там работает разбиение.
            case 'round':
            case 'tworound': {
                // Ноль снимаем ровно у ОДНОГО множителя, даже если круглые оба:
                // 30 × 20 превращается в 3 × 20, и «допиши ноль» остаётся правдой.
                if (a % 10 === 0) return { key: 'mul:round', args: [a / 10, b] };
                if (b % 10 === 0) return { key: 'mul:round', args: [a, b / 10] };
                return null;
            }
            case 'twoPlain':
            case 'twoCarry': {
                const two = hi, one = lo;                // lo здесь всегда однозначный
                const tens = Math.floor(two / 10) * 10, units = two % 10;
                if (!tens || !units) return null;        // разбивать нечего
                return { key: 'mul:twoSplit', args: [tens, one, units] };
            }
            default: return null;
        }
    }

    if (op === 'div') {
        if (b === 0) return { key: 'div:byZero', args: [] };
        if (a === 0) return { key: 'div:zeroTop', args: [] };
        // ÷1, ÷10 и a ÷ a — приёма нет, как и у ×1. «На что умножить 1, чтобы вышло 8?»
        // не подсказка, а издёвка; а «убери ноль» у 40 ÷ 10 просто выдаёт ответ.
        if (struct.cls === 'triv') return null;
        // «Убери по нулю» работает, только если ноль есть у обоих: 210 ÷ 7 так не берётся.
        // И только если сокращённый делитель НЕ СОВПАЛ С ОТВЕТОМ: у 40 ÷ 20 подсказка
        // «Убери по нулю: 4 ÷ 2» печатает двойку, а два и есть ответ, и ребёнку,
        // который просто читает последнее число, считать уже нечего. Та же болезнь,
        // что была у спуска к десятку и у вычитания через сотню. Редко — около 2% всех
        // подсказок деления — и чинится тем же: уходим в общий приём, где печатаются
        // только числа самого примера. Молчания при этом не появляется.
        // Сравниваем МОДУЛИ: у −160 ÷ 40 сокращённый делитель 4, а ответ −4, и знаки
        // разные — но на экране всё равно стоит четвёрка рядом с ответом «минус четыре».
        if (a % 10 === 0 && b % 10 === 0 && Math.abs(b / 10) !== Math.abs(a / b)) {
            return { key: 'div:round', args: [a / 10, b / 10] };
        }
        return { key: 'div:general', args: [b, a] };
    }
    return null;
}

// Готовая строка для экрана. Пустая означает «приёма нет» — это законный исход,
// а не сбой: молчание лучше выдуманного правила.
function trickHint(meta, problem) {
    try {
        const pick = trickPick(meta, problem);
        if (!pick) return '';
        const table = resolveTricks();
        const tpl = table && table[pick.key];
        if (!tpl) return '';
        let out = tpl;
        pick.args.forEach((v, i) => { out = out.split('%' + (i + 1)).join(String(v)); });
        // Осталась неподставленная %N — шаблон и аргументы разъехались. Показывать
        // такое ученику нельзя, как и в подсказках по ошибкам.
        return /%\d/.test(out) ? '' : out;
    } catch (e) {
        return '';
    }
}
