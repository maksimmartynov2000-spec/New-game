// Пары модулей для класса «сложение модулей»: оба не меньше минимума, сумма не
// больше потолка. Перечисляем и берём равномерно. Последовательный розыгрыш
// («сначала первый модуль, потом второй из остатка») сужает выбор вслед за
// первым числом, и на краю остаётся единственный вариант: в модели «−7 − 3»
// забирал 9,5% первой звезды — каждый одиннадцатый пример.
const NEG_SUM_PAIRS = (() => {
    const out = {};
    for (let lvl = 1; lvl <= 5; lvl++) {
        const R = NEG_ADD_RANGE[lvl], MIN = NEG_ADD_MIN[lvl], list = [];
        for (let m1 = MIN; m1 <= R - MIN; m1++) {
            for (let m2 = MIN; m2 <= R - m1; m2++) list.push([m1, m2]);
        }
        out[lvl] = list;
    }
    return out;
})();

function pickNegAddClass(level) {
    const sh = NEG_ADD_CLASS_SHARES[level] || NEG_ADD_CLASS_SHARES[5];
    let r = Math.random();
    for (let i = 0; i < sh.length; i++) { r -= sh[i]; if (r < 0) return i; }
    return sh.length - 1;
}

// Модули по классу. Возвращает [модуль первого, модуль второго].
function negAddMagnitudes(level, cls) {
    if (cls === 0) {
        const list = NEG_SUM_PAIRS[level];
        return list[randInt(0, list.length - 1)];
    }
    const R = NEG_ADD_RANGE[level], MIN = NEG_ADD_MIN[level];
    // Равные модули дали бы ответ 0 и не относятся ни к «дошёл», ни к «перешёл».
    let m1, m2;
    do { m1 = randInt(MIN, R); m2 = randInt(MIN, R); } while (m1 === m2);
    const hi = Math.max(m1, m2), lo = Math.min(m1, m2);
    return cls === 1 ? [hi, lo] : [lo, hi];   // 1 — не дошёл, 2 — перешёл
}

// Общее тело сложения и вычитания. Клетки у них разные, поэтому оператор ЗАДАН
// снаружи, а не выбирается: в клетке «Сложение» выражение всегда «n1 + n2».
//
// Скобки при этом решаются ПЕРВЫМИ, и под решение подбирается знак второго
// числа. Видимые скобки означают отрицательное n2 — а в клетке сложения это
// y < 0, в клетке вычитания наоборот y > 0 (потому что там n2 = −y). Так доля
// скобок становится свободной величиной, а не побочным следствием знаков.
//
// Когда скобок нет, минус обязан быть виден иначе — поэтому отрицательным
// делается первое число. Исключение — те самые 5% простых примеров.
function genAddSubNegative(level, isSub) {
    const cls = pickNegAddClass(level);
    const mags = negAddMagnitudes(level, cls);
    const wantParen = Math.random() < (NEG_PAREN_SHARE[level] || 0);
    const plain = !wantParen && Math.random() < NEG_ADD_PLAIN_SHARE;

    // Знак ВТОРОГО слагаемого в приведённом виде «x + y».
    let ys;
    if (wantParen) ys = isSub ? 1 : -1;        // скобки требуют отрицательного n2
    else if (plain) ys = isSub ? -1 : 1;       // ни одного минуса в записи
    else ys = (cls === 0) ? -1 : 1;            // минус уводим в первое число

    // Знак первого определяется классом: у «сложения модулей» он совпадает со
    // вторым, у остальных двух — противоположен.
    const xs = (cls === 0) ? ys : -ys;

    const x = mags[0] * xs, y = mags[1] * ys;
    const n1 = x, n2 = isSub ? -y : y;
    const showParen = wantParen && n2 < 0;
    return {
        text: formatAddSubText(n1, isSub ? '-' : '+', n2, showParen),
        answer: x + y, a: n1, b: n2
    };
}

function genAddNegative(level) { return genAddSubNegative(level, false); }
function genSubNegative(level) { return genAddSubNegative(level, true); }

// ===================== ОТРИЦАТЕЛЬНЫЕ УМНОЖЕНИЕ И ДЕЛЕНИЕ =====================
//
// Здесь знак — НЕ содержание. Правило «одинаковые дают плюс, разные минус»
// осваивается за один урок и дальше просто применяется; вся оставшаяся работа
// арифметическая, то есть ровно та, что уже разобрана у положительных. Поэтому
// отрицательное умножение — это положительное умножение плюс знак, а
// отрицательное деление — положительное деление плюс знак. Своих таблиц у них
// больше нет: MUL_TABLE, DIVISOR_POOL и QUOTIENT_MAX держались только ради них.
//
// Что это чинит. Старая схема брала первый множитель из списка вида {1,2,5,10},
// а второй наугад до десяти. Замер: на первой звезде 61,6% примеров не требовали
// счёта вообще (×0, ×1, ×10), а на четвёртой и пятой таблицы умножения не было
// ВОВСЕ — там первый множитель шёл из 10…20 и 10…99, и факты таблицы просто
// выпадали. Примеры выглядели как «−33 × 1» и «−52 × 10». У деления то же самое:
// 57,8% без счёта на первой звезде.
//
// Почему НЕ зеркалим положительные целиком. Двузначного на однозначное
// («−78 × (−7)») здесь нет намеренно. Если арифметика идёт на пределе, знак
// приписывается в последний момент почти не думая — то есть навык, ради которого
// раздел существует, тренируется хуже всего там, где считается самым сложным.
// Потолок отрицательных — таблица и круглые. При вдвое более коротком примере
// за то же время выходит вдвое больше знаковых решений.
//
// Пятая звезда. У положительных её занимает двузначное на однозначное, а его мы
// не берём. Содержание ей даёт «двузначное на круглое» (−24 × (−30), −720 ÷ (−30)):
// приём «убрать ноль и посчитать» лёгкий, то есть принципу не противоречит, но
// без него пятая звезда оказывалась ТОЧНОЙ копией четвёртой — замер показывал
// 1153 разных примера против 1155.
// Пятая звезда: три множителя. Правило знаков здесь ОБОБЩАЕТСЯ — считаем минусы,
// чётное число даёт плюс, нечётное минус. Это настоящий новый навык, а не более
// крупные числа: произведение держим не выше двухсот, чтобы арифметика осталась
// мелкой и голова была занята знаками.
//
// Множители от 2 до 10, произведение до 200 — таких троек ровно 97, это
// сопоставимо с 36 фактами таблицы и на треть звезды хватает с запасом.
const MUL_TRIPLES = (() => {
    const out = [];
    for (let x = 2; x <= 10; x++) {
        for (let y = x; y <= 10; y++) {
            for (let z = y; z <= 10; z++) {
                if (x * y * z <= 200) out.push([x, y, z]);
            }
        }
    }
    return out;
})();

// Знаки трёх множителей. «Все плюсы» — такая же редкость, как и в паре: пример
// без единого минуса в разделе отрицательных чисел выглядит случайно попавшим.
function tripleSigns() {
    for (let guard = 0; guard < 40; guard++) {
        const s = [0, 0, 0].map(() => (Math.random() < 0.5 ? 1 : -1));
        if (s.some(v => v < 0) || Math.random() < 0.05) return s;
    }
    return [-1, 1, 1];
}

// Запись: у первого множителя знак стоит как есть, у следующих отрицательные
// берутся в скобки — «−8 × 3 × (−8)».
function formatFactors(vals) {
    return vals.map((v, i) => (i > 0 && v < 0) ? `(${v})` : String(v)).join(' × ');
}

