function randInt(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function randSign() { return Math.random() < 0.5 ? -1 : 1; }
function fmt(n) { return n < 0 ? `(${n})` : `${n}`; }

// Для +/- со вторым отрицательным операндом обычно не пишем "5 + (-6)", а сразу
// переворачиваем оператор и показываем модуль: "5 - 6". НО на 5★ это явление —
// "двойной знак" — намеренно оставляем как есть ("5 + (-6)"), это элемент сложности
// именно старшего уровня (нужно распознать и разобрать двойной знак).
function formatAddSubText(n1, opSymbol, n2, keepDoubleSign) {
    if (n2 < 0) {
        if (keepDoubleSign) {
            return `${n1} ${opSymbol} (${n2})`;
        }
        const flipped = opSymbol === '+' ? '-' : '+';
        return `${n1} ${flipped} ${Math.abs(n2)}`;
    }
    return `${n1} ${opSymbol} ${n2}`;
}

