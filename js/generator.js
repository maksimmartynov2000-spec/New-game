// СЛОЖЕНИЕ: полосы сумм, переход через десяток, размер слагаемых.
//
// Потолки прежние (10-20-50-100-200), но внутри потолка сумма больше не берётся
// равномерно. Раньше сумма 3 (два разных примера) получала ровно столько же шансов,
// сколько сумма 180 (сто семьдесят девять примеров), — и на пятой звезде каждый
// десятый пример был примером с первой. Теперь у каждой полосы своя частота.
// Таблицы ниже общие для сложения и вычитания: у вычитания роль суммы играет
// уменьшаемое, роль слагаемых — вычитаемое и ответ. См. genSubPositive.
const ADD_BANDS = [[2, 10], [11, 20], [21, 50], [51, 100], [101, 200]];
const ADD_BAND_WEIGHTS = {
    1: [1],
    2: [0.30, 0.70],
    3: [0.10, 0.20, 0.70],
    4: [0.05, 0.10, 0.15, 0.70],
    5: [0.01, 0.04, 0.125, 0.225, 0.60]
};

// Класс примера — по сумме ПОСЛЕДНИХ ЦИФР двух чисел. Их три, и это три разных
// навыка, а не два:
//
//   меньше 10  — без перехода            5 + 22, 30 + 20
//   ровно 10   — дополнение до круглого  7 + 13, 36 + 4, 88 + 12
//   больше 10  — полный переход          7 + 15, 27 + 18
//
// Средний класс раньше растворялся в первом и таял к старшим звёздам: его доля
// падала с 20% на 1★ до 4,8% на 5★, хотя «дополнить до круглого» — приём, которым
// считают всю жизнь. Теперь у него своя доля.
//
// Заметь, что 30 + 20 в средний класс НЕ попадает: сумма единиц там ноль, а не
// десять. Это сложение десятков, ему место в первом классе, где его придержит порог.
const ADD_CLASS_SHARES = [0.20, 0.10, 0.70];
// В полосе 2–10 полного перехода не бывает вовсе: сумма единиц равна самой сумме,
// а она не больше десяти. Средний класс там — это ровно девять пар состава десятка
// (1+9 … 9+1), и они главный сюжет первой звезды.
const ADD_CLASS_SHARES_SMALL = [0.70, 0.30, 0];

// Вес малых слагаемых в полосе 2–10.
//
// Равномерный выбор среди пар сам по себе перекошен: при сумме S меньшее слагаемое
// пробегает от 1 до S/2, поэтому единица встречается во всех суммах, а пятёрка —
// только в десятке. Из 45 пар полосы в 17 одно из слагаемых равно единице, и первая
// звезда на 38% состояла из «прибавить один».
//
// Вес равен меньшему слагаемому, но не больше трёх. Без потолка вся группа
// «меньшее = 5» состоит из единственной пары 5 + 5, и она забирала бы 5,2% звезды —
// больше, чем было у любого примера с единицей. С потолком ни один пример
// не вылезает, а доля единицы падает с 38% примерно до 22%.
//
// К классу дополнения до круглого вес НЕ применяется: девять фактов состава
// десятка должны идти поровну, иначе самым частым станет самый лёгкий из них.
const SMALL_BAND_WEIGHT_CAP = 3;

// Нижняя граница меньшего слагаемого — ТОЛЬКО для класса без перехода.
// В двух других классах маленькое слагаемое пример не обесценивает: 156 + 9 надо
// считать, 36 + 4 тоже. Без перехода обесценивает: 156 + 3 считать не надо.
const ADD_MIN_ADDEND = [1, 5, 8, 14, 24];

// 0 — без перехода, 1 — дополнение до круглого, 2 — полный переход.
// Для вычитания сгодится он же: a − b = c это та же тройка, что b + c = a,
// и класс считается по вычитаемому с ответом.
function unitsClass(x, y) {
    const s = (x % 10) + (y % 10);
    return s < 10 ? 0 : (s === 10 ? 1 : 2);
}

// Выбор по долям. Возвращает последний ненулевой индекс, если сумма долей
// из-за плавающей арифметики оказалась чуть меньше единицы.
function pickByShare(shares) {
    let r = Math.random(), last = 0;
    for (let i = 0; i < shares.length; i++) {
        if (shares[i] > 0) last = i;
        r -= shares[i];
        if (r < 0) return i;
    }
    return last;
}

function genAddPositive(level) {
    const bi = pickByShare(ADD_BAND_WEIGHTS[level]);
    const lo = ADD_BANDS[bi][0], hi = ADD_BANDS[bi][1];

    const wantClass = pickByShare(bi === 0 ? ADD_CLASS_SHARES_SMALL : ADD_CLASS_SHARES);
    const minAddend = wantClass === 0 ? ADD_MIN_ADDEND[bi] : 1;

    // Отбор с повторной попыткой. Каждая попытка — равномерная точка среди всех
    // пар полосы, а отбор из равномерного остаётся равномерным, поэтому уцелевшие
    // примеры распределены ровно. Это важнее, чем кажется: при старой схеме
    // «сумма равномерно, потом разбить» малые суммы получали вес не по числу
    // своих примеров, и разнообразие проседало на всех звёздах.
    // Тысяча попыток, а не двести: самый узкий случай — дополнение до круглого
    // в полосе 101–200, где годных пар всего 3,5% от квадрата, и двухсот попыток
    // не хватало примерно раз на четырнадцать тысяч примеров.
    for (let t = 0; t < 1000; t++) {
        const n1 = randInt(1, hi - 1), n2 = randInt(1, hi - 1);
        const sum = n1 + n2;
        if (sum < lo || sum > hi) continue;
        if (unitsClass(n1, n2) !== wantClass) continue;
        if (Math.min(n1, n2) < minAddend) continue;
        if (bi === 0 && wantClass === 0
            && randInt(1, SMALL_BAND_WEIGHT_CAP) > Math.min(n1, n2)) continue;
        return { text: `${n1} + ${n2}`, answer: sum, a: n1, b: n2 };
    }

    // Страховка: пример должен быть всегда. Снимаем требование по классу, но НЕ
    // по размеру слагаемых — иначе редкий сбой отбора протаскивает ровно те
    // примеры, ради отсева которых порог и заведён. В полосу и в порог попадаем
    // гарантированно: нижняя граница любой полосы вдвое больше своего порога.
    const sum = randInt(lo, hi);
    const n1 = randInt(minAddend, sum - minAddend);
    return { text: `${n1} + ${sum - n1}`, answer: sum, a: n1, b: sum - n1 };
}

// ВЫЧИТАНИЕ устроено ровно так же, как сложение, и это не подгонка.
// «a − b = c» — та же тройка чисел, что «b + c = a»: уменьшаемое играет роль суммы,
// вычитаемое и ответ — роль двух слагаемых. Поэтому полосы задаются по уменьшаемому,
// а класс считает тот же unitsClass по вычитаемому и ответу:
//
//   меньше 10  — без заёма              27 − 5, 50 − 20
//   ровно 10   — вычитание из круглого  20 − 7, 100 − 37
//   больше 10  — полный заём            22 − 7
//
// Заём и перенос — одно и то же событие. По разряду единиц b%10 + c%10 = a%10 + 10·k,
// поэтому перенос при сложении возникает ровно тогда, когда при вычитании нужен заём.
// Из этого же следует, что на первой звезде полного заёма нет, а «10 − 7» попадает
// в средний класс — это состав десятка, а не переход через него.
//
// Вычитаемое и ответ всегда не меньше единицы. Раньше вычитаемое бралось от нуля до
// уменьшаемого, и «7 − 0» с «7 − 7» выпадали с одинаковой вероятностью 1/(a+1) —
// вместе треть всех примеров первой звезды. Ни то, ни другое ничему не учит.
function genSubPositive(level) {
    const bi = pickByShare(ADD_BAND_WEIGHTS[level]);
    const lo = ADD_BANDS[bi][0], hi = ADD_BANDS[bi][1];
    const wantClass = pickByShare(bi === 0 ? ADD_CLASS_SHARES_SMALL : ADD_CLASS_SHARES);
    const minPart = wantClass === 0 ? ADD_MIN_ADDEND[bi] : 1;

    // Отбор идёт по паре «вычитаемое и ответ» — то есть по двум слагаемым зеркала.
    // Каждая попытка равномерна среди всех пар полосы, а отбор из равномерного
    // остаётся равномерным.
    for (let t = 0; t < 1000; t++) {
        const n2 = randInt(1, hi - 1), diff = randInt(1, hi - 1);
        const n1 = n2 + diff;
        if (n1 < lo || n1 > hi) continue;
        if (unitsClass(n2, diff) !== wantClass) continue;
        if (Math.min(n2, diff) < minPart) continue;
        if (bi === 0 && wantClass === 0
            && randInt(1, SMALL_BAND_WEIGHT_CAP) > Math.min(n2, diff)) continue;
        return { text: `${n1} - ${n2}`, answer: diff, a: n1, b: n2 };
    }

    // Страховка: снимаем требование по классу, но не по размеру. Нижняя граница
    // любой полосы вдвое больше своего порога, поэтому годная пара найдётся всегда.
    const n1 = randInt(lo, hi);
    const n2 = randInt(minPart, n1 - minPart);
    return { text: `${n1} - ${n2}`, answer: n1 - n2, a: n1, b: n2 };
}

// Какая группа выпала. Доли — из MUL_SHARES, порядок в массиве и есть порядок
// розыгрыша, поэтому суммы обязаны давать единицу (тест это стережёт).
function pickMulGroup(level) {
    const rows = MUL_SHARES[level] || MUL_SHARES[5];
    let r = Math.random();
    for (let i = 0; i < rows.length; i++) {
        r -= rows[i][1];
        if (r < 0) return rows[i][0];
    }
    return rows[rows.length - 1][0];
}

function pickMulFact(list) {
    return list[randInt(0, list.length - 1)];
}

// Двузначное на однозначное. Полосу выбираем ОДИН раз, а перебираем уже внутри
// неё: если перевыбирать полосу на каждой попытке, её вес перестанет быть тем,
// что записано. Внутри полосы годная пара находится примерно в пятой части
// случаев даже для более редкого исхода «без переноса», так что тысячи попыток
// хватает с колоссальным запасом.
function genMulTwoDigit(wantCarry) {
    const bi = pickByShare(MUL_TWO_BAND_WEIGHTS);
    const lo = MUL_TWO_BANDS[bi][0], hi = MUL_TWO_BANDS[bi][1];
    for (let t = 0; t < 1000; t++) {
        const a = randInt(lo, hi), b = randInt(2, 9);
        if (a % 10 === 0) continue;                       // круглые — своя группа
        if (((a % 10) * b >= 10) !== wantCarry) continue;
        return [a, b];
    }
    // Страховка: снимаем требование по переносу, но не по полосе.
    for (let t = 0; t < 100; t++) {
        const a = randInt(lo, hi);
        if (a % 10 !== 0) return [a, randInt(2, 9)];
    }
    return [lo + 1, randInt(2, 9)];
}

function genMulPositive(level) {
    const group = pickMulGroup(level);
    // Продолжение двойки (2 × 11…15) и двузначное на круглое разбираются
    // в mulPairForGroup — она общая с отрицательным режимом.
    const pair = (group === 'twoPlain' || group === 'twoCarry')
        ? genMulTwoDigit(group === 'twoCarry')
        : mulPairForGroup(group);

    // Порядок случайный: «тринадцать умножить на два» и «два умножить на
    // тринадцать» читаются по-разному, и вторая форма встречается реже, значит
    // и даётся труднее.
    const swap = Math.random() < 0.5;
    const a = swap ? pair[1] : pair[0];
    const b = swap ? pair[0] : pair[1];
    return { text: `${a} × ${b}`, answer: a * b, a, b };
}

function pickDivGroup(level) {
    const rows = DIV_SHARES[level] || DIV_SHARES[5];
    let r = Math.random();
    for (let i = 0; i < rows.length; i++) {
        r -= rows[i][1];
        if (r < 0) return rows[i][0];
    }
    return rows[rows.length - 1][0];
}

function genDivPositive(level) {
    const group = pickDivGroup(level);

    if (group === 'zero') {
        // Делимое случайное: иначе «на ноль» узнавалось бы по самому числу,
        // а не по делителю.
        const dividend = randInt(2, 99);
        return { text: `${dividend} ÷ 0`, answer: null, noSolution: true, a: dividend, b: 0 };
    }

    let pair;
    if (group === 'two') {
        pair = pickMulFact(Math.random() < MUL_TWO_EXT_SHARE
            ? DIV_GROUPS.twoExt : DIV_GROUPS.two);
    } else if (group === 'tworound') {
        pair = pickMulFact(DIV_TWO_ROUND);
    } else if (group === 'twoPlain' || group === 'twoCarry') {
        // Зеркало двузначного на однозначное: частное двузначное, делитель
        // однозначный. Признак «надо сносить» тот же, что перенос в умножении:
        // 84 ÷ 7 = 12, потому что 12 × 7 идёт с переносом.
        const mul = genMulTwoDigit(group === 'twoCarry');
        pair = [mul[0] * mul[1], mul[1]];
    } else {
        pair = pickMulFact(DIV_GROUPS[group]);
    }

    const dividend = pair[0], divisor = pair[1];
    return { text: `${dividend} ÷ ${divisor}`, answer: dividend / divisor, a: dividend, b: divisor };
}

// --- ОТРИЦАТЕЛЬНЫЕ ЧИСЛА ---
function genMulNegative(level) {
    // Умножение на ноль отдельным случаем больше не нужно: ноль входит в группу
    // «без счёта» наравне с единицей и десяткой и получает её долю.
    const group = pickFromShares(NEG_MUL_SHARES[level] || NEG_MUL_SHARES[5]);

    if (group === 'triple') {
        const t = shuffleArray(pickMulFact(MUL_TRIPLES).slice());
        const sg = tripleSigns();
        const vals = t.map((v, i) => v * sg[i]);
        const answer = vals[0] * vals[1] * vals[2];
        // Наружу отдаём разложение на ДВА числа, произведение которых равно
        // ответу: вся машинерия вариантов ответа считает, что a × b = ответ, и
        // ломать это ради записи из трёх чисел незачем. Частичное произведение
        // при этом само по себе хорошая ловушка — «перемножил только два».
        return {
            text: formatFactors(vals), answer,
            a: vals[0] * vals[1], b: vals[2], triple: true
        };
    }

    const pair = mulPairForGroup(group, true);
    const swap = Math.random() < 0.5;
    const magA = swap ? pair[1] : pair[0];
    const magB = swap ? pair[0] : pair[1];
    const [s1, s2] = comboToSigns(pickIntegerSignCombo('mul', level));
    const a = magA * s1;
    const b = magB * s2;
    return { text: `${a} × ${fmt(b)}`, answer: a * b, a: a, b: b };
}

function genDivNegative(level) {
    const group = pickFromShares(NEG_DIV_SHARES[level] || NEG_DIV_SHARES[5]);

    if (group === 'zero') {
        // «На ноль делить нельзя» — правило, а не пример, и доля у него теперь
        // убывающая, как у положительных, а не фиксированные 4% всю игру.
        const dividend = randInt(2, 99) * randSign();
        return { text: `${dividend} ÷ 0`, answer: null, noSolution: true, a: dividend, b: 0 };
    }

    // Пара берётся у положительного деления — там уже перечислены именно ЗАДАЧИ
    // НА ДЕЛЕНИЕ, а не факты умножения, поэтому квадраты не перекошены.
    let pair;
    if (group === 'two') {
        pair = pickMulFact(Math.random() < MUL_TWO_EXT_SHARE
            ? DIV_GROUPS.twoExt : DIV_GROUPS.two);
    } else if (group === 'tworound') {
        pair = pickMulFact(DIV_TWO_ROUND);
    } else if (group === 'triv') {
        pair = pickMulFact(NEG_TRIV_DIV);
    } else {
        // Незнакомая группа не роняет генератор — по той же причине, что и в
        // умножении: опечатку в таблице долей ловят проверки, а не ученик.
        pair = pickMulFact(DIV_GROUPS[group] || DIV_GROUPS.small);
    }

    // Знаки те же, что и раньше: s1 — знак делителя, s2 — знак частного, а знак
    // делимого получается из них. Так знак ОТВЕТА остаётся управляемым.
    const [s1, s2] = comboToSigns(pickIntegerSignCombo('div', level));
    const quotientMag = pair[0] / pair[1];
    const divisor = pair[1] * s1;
    const quotient = quotientMag === 0 ? 0 : quotientMag * s2;
    const dividend = divisor * quotient;
    return { text: `${dividend} ÷ ${fmt(divisor)}`, answer: quotient, a: dividend, b: divisor };
}

// --- ГЕНЕРАЦИЯ ОТВЛЕКАЮЩИХ ВАРИАНТОВ ОТВЕТА ---
// Функция работает через МОДУЛЬ чисел (не зависит от знака a/b) — так ловушка
// "ошибка в разрядах" работает и в отрицательном режиме тоже. Знак результата
// применяется на стороне вызова (buildDistractors), обычно совпадающим со знаком
// правильного ответа — это изолирует "ошибку в цифрах" от "ошибки в знаке".
// Имитация "вычитания без заёма через разряд" — частая ошибка новичков:
// по каждому разряду берут модуль разности цифр, не занимая десяток
function noBorrowSub(a, b) {
    const sa = String(Math.abs(a)), sb = String(Math.abs(b));
    const maxLen = Math.max(sa.length, sb.length);
    const pa = sa.padStart(maxLen, '0');
    const pb = sb.padStart(maxLen, '0');
    let digits = '';
    for (let i = 0; i < maxLen; i++) {
        digits += Math.abs(parseInt(pa[i]) - parseInt(pb[i]));
    }
    const val = parseInt(digits, 10);
    return Number.isNaN(val) ? null : val;
}

// --- ПРАВДОПОДОБИЕ ЛОВУШКИ ---
// Вариант ответа обязан быть тем, что ученик мог бы получить, посчитав неверно.
// Для положительных чисел это проверяется самой арифметикой: сумма всегда больше
// каждого слагаемого, разность всегда меньше уменьшаемого. Вариант, нарушающий
// это, отбрасывается одним взглядом — он занимает слот и ничего не проверяет
// (6 + 8 с вариантом 4, 14 − 10 с вариантом 14).
//
// В отрицательном режиме правила другие: −5 + (−8) = −13 меньше обоих слагаемых.
// Поэтому там фильтр не применяется вовсе — этот раздел разберём отдельно.
function plausibleWhole(opKey, a, b, val, isNegative) {
    if (isNegative) return true;
    if (!Number.isFinite(val) || val < 0) return false;
    if (typeof a !== 'number' || typeof b !== 'number') return true;
    if (opKey === 'add') return val > Math.max(a, b);
    if (opKey === 'sub') return val < a && val !== b;
    return true;
}

// Ловушка «промахнулся на десяток»: единицы посчитаны верно, десятки — нет
// (17 + 18 = 35, а названо 45 или 25). Это самая частая ошибка при счёте в столбик
// и одновременно единственный способ закрыть ярлык «посчитай только единицы»:
// пока среди вариантов нет второго числа с той же последней цифрой, ответ можно
// взять, посчитав один разряд из двух.
function tenDecoyFor(opKey, a, b, correctAnswer, isNegative) {
    if (isNegative || correctAnswer < 11) return null;   // десятков нет — и ловушки нет
    const up = correctAnswer + 10;
    const down = correctAnswer - 10;
    const okUp = plausibleWhole(opKey, a, b, up, isNegative);
    const okDown = down > 0 && plausibleWhole(opKey, a, b, down, isNegative);
    if (okUp && okDown) return Math.random() < 0.6 ? up : down;   // 60% в большую сторону
    if (okUp) return up;
    if (okDown) return down;
    return null;
}

// Ловушка «та же последняя цифра» для умножения и деления.
//
// У сложения и вычитания она есть давно (tenDecoyFor) и работает: замер даёт
// 0,3–4,9% примеров, где верную последнюю цифру имеет ровно один вариант.
// У умножения таких примеров было 74–88%, у деления 76–80% — то есть посчитать
// единицы произведения и выбрать единственный подходящий вариант хватало почти
// всегда, а десятки можно было не считать вовсе. «7 × 13 = 91» при вариантах
// 20, 78, 84, 91: семью три — двадцать один, единица одна, ответ найден.
//
// Годится любое смещение, кратное десяти: оно не трогает последнюю цифру.
// Самое честное — «не учёл десяток второго множителя»: 7 × 3 = 21 против
// 7 × 13 = 91. Разница ровно 10·a, и это настоящая ошибка, а не выдумка.
// Для табличных фактов такой сдвиг слишком велик, поэтому там берётся обычная
// десятка: 42 против 32 и 52.
function sameUnitsDecoy(opKey, a, b, correctAnswer, isNegative) {
    if (isNegative) return null;                 // у отрицательных свой набор — две пары модулей
    if (opKey !== 'mul' && opKey !== 'div') return null;
    if (!Number.isFinite(correctAnswer) || Math.abs(correctAnswer) < 10) return null;
    const steps = [10];
    const lo = Math.min(Math.abs(a), Math.abs(b));
    if (opKey === 'mul' && lo > 1 && lo <= 9) steps.push(10 * lo);
    const cand = [];
    steps.forEach(st => {
        [correctAnswer + st, correctAnswer - st].forEach(v => {
            if (v <= 0 || v === correctAnswer || v === a || v === b) return;
            if (!plausibleWhole(opKey, a, b, v, isNegative)) return;
            if (cand.indexOf(v) < 0) cand.push(v);
        });
    });
    if (!cand.length) return null;
    return cand[randInt(0, cand.length - 1)];
}

// Число с теми же десятками, что у tensSource, и другой цифрой единиц.
function unitsDecoyValue(tensSource, correctAnswer, shift) {
    const unit = ((correctAnswer % 10) + shift + 10) % 10;
    return Math.floor(tensSource / 10) * 10 + unit;
}

// Десяточная ловушка закрывает счёт по единицам, единичная («те же десятки, другая
// цифра единиц») — прикидку на глаз. Но вместе они создают третий ярлык: верный
// ответ оказывается единственным числом, связанным сразу с двумя другими — общие
// десятки с одной ловушкой, общие единицы с другой, — и его видно, не считая.
//
// Поэтому пара достраивается до квадрата 2×2: два десятка × две цифры единиц,
// 35 / 45 / 37 / 47. Верную последнюю цифру носят двое, верный десяток — тоже
// двое, связи у всех четырёх одинаковы. Угадать нельзя: надо посчитать оба разряда.
//
// Сначала квадрат строился не всегда, а в 70% примеров — ради разнообразия
// картинки. Замер показал, что так не работает: в оставшихся 30% обычный
// случайный вариант попадает в тот же десяток, что и ответ, и подсказка
// возвращается (26–40% примеров вместо ожидаемых 7–12%). Поэтому квадрат
// строится всегда, когда это возможно.

function addSubDecoyPlan(opKey, a, b, correctAnswer, isNegative) {
    const out = [];
    if (isNegative || (opKey !== 'add' && opKey !== 'sub')) return out;
    if (typeof a !== 'number' || typeof b !== 'number') return out;
    const keep = (v) => v !== correctAnswer && !out.includes(v)
        && plausibleWhole(opKey, a, b, v, isNegative);

    // Ответ меньше одиннадцати — промахиваться на десяток не на чем. Вместо этого
    // соседние числа по разные стороны: на первой звезде надо считать точно,
    // а не прикидывать, и разброс вариантов не должен давать угадать порядком.
    if (correctAnswer <= 10) {
        const side = Math.random() < 0.5 ? 1 : -1;
        const near = [correctAnswer + side * randInt(1, 2)];
        if (Math.random() >= 0.4) near.push(correctAnswer - side * randInt(1, 2));
        near.forEach(v => { if (keep(v)) out.push(v); });
        const wide = correctAnswer + (Math.random() < 0.5 ? 1 : -1) * randInt(3, 5);
        if (keep(wide)) out.push(wide);
        return out;
    }

    const ten = tenDecoyFor(opKey, a, b, correctAnswer, isNegative);
    if (ten === null) return out;
    out.push(ten);

    // Сдвиг цифры единиц ровно на 1–3: вариант стоит вплотную к ответу, но не
    // читается как опечатка. Перебираем сдвиги вразнобой — у краёв диапазона
    // часть из них даёт невозможные числа, и с одной попытки квадрат не собрать.
    const shifts = shuffleArray([1, 2, 3, -1, -2, -3]);
    for (const shift of shifts) {
        const u1 = unitsDecoyValue(correctAnswer, correctAnswer, shift);
        const u2 = unitsDecoyValue(ten, correctAnswer, shift);
        if (u1 !== u2 && keep(u1) && keep(u2)) { out.push(u1); out.push(u2); break; }
    }
    return out;
}

function pushStructural(arr, val, correctAnswer, isNegative) {
    if (val === undefined || val === null || !Number.isFinite(val)) return;
    val = Math.round(val);
    if (val === correctAnswer) return;
    if (!isNegative && val < 0) return;
    if (arr.includes(val)) return;
    arr.push(val);
}

function shuffleArray(arr) {
    const copy = arr.slice();
    for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
}

function buildDistractors(opKey, a, b, correctAnswer, isNegative, count, level) {
    // ===== ПРИОРИТЕТ 1: самые частые реальные ошибки =====
    let priority = [];

    // Знаковой ловушки («верный модуль, неверный знак») здесь больше нет: в
    // отрицательном режиме она приходит из самой пары модулей ниже, а в режиме
    // «без пар» подмешивать её нельзя — она и создавала бы ту единственную пару,
    // по которой ответ читался без счёта.

    // Разрядные ловушки сложения и вычитания положительных: промах на десяток
    // и, в большинстве примеров, парная к нему единичная. Приоритет высокий —
    // без них ответ угадывается по одному разряду, см. addSubDecoyPlan.
    addSubDecoyPlan(opKey, a, b, correctAnswer, isNegative)
        .forEach(v => pushStructural(priority, v, correctAnswer, isNegative));

    // То же самое для умножения и деления: без второго числа с той же последней
    // цифрой ответ берётся счётом одного разряда из двух.
    const unitsTwin = sameUnitsDecoy(opKey, a, b, correctAnswer, isNegative);
    if (unitsTwin !== null) pushStructural(priority, unitsTwin, correctAnswer, isNegative);

    // Умножение: один из множителей — 0 → берут второй множитель "как есть"
    // (путают с умножением на 1)
    if (opKey === 'mul') {
        if (a === 0 && b !== 0) pushStructural(priority, b, correctAnswer, isNegative);
        else if (b === 0 && a !== 0) pushStructural(priority, a, correctAnswer, isNegative);
    }

    // Деление: «Нет решения» как вариант. Раньше он подмешивался только при
    // нулевом частном плюс один процент наугад — и это была прямая лазейка мимо
    // счёта. Замер: на пятой звезде вариант показывался в 12,7% примеров и в 79%
    // из них оказывался верным. То есть «вижу „Нет решения“ — жму» давало четыре
    // попадания из пяти.
    //
    // Причина: доля самих примеров «÷ 0» была фиксированной, а приманок с ростом
    // звезды становилось меньше. Теперь приманка считается ОТ доли «÷ 0»: вариант
    // показывается примерно вчетверо чаще, чем бывает верным. При четырёх кнопках
    // это ровно случайный уровень — увидел и всё равно надо считать.
    const NO_SOLUTION_DECOY_FACTOR = 4;
    let includeNoSolutionDecoy = false;
    if (opKey === 'div') {
        if (correctAnswer === 0) {
            // Нулевое частное: 0 ÷ 7 = 0. Здесь вариант обязателен — это и есть
            // путаница с правилом «на ноль делить нельзя».
            includeNoSolutionDecoy = true;
        } else {
            const zeroShare = DIV_ZERO_SHARES[level] || DIV_ZERO_SHARES[5];
            // Доля приманок среди ОСТАЛЬНЫХ примеров: столько, чтобы вместе с
            // настоящими «÷ 0» вариант был верен примерно в четверти показов.
            const need = zeroShare * (NO_SOLUTION_DECOY_FACTOR - 1) / (1 - zeroShare);
            if (Math.random() < need) includeNoSolutionDecoy = true;
        }
    }

    // ===== ПРИОРИТЕТ 2: типовые структурные ошибки по операциям =====
    let structural = [];

    if (opKey === 'add') {
        // Модель «сложил столбиком, забыл перенос» раньше строилась поразрядно по
        // всем разрядам сразу. При одном переносе это ровно «ответ − 10» (17 + 18 → 25),
        // а при двух давало мусор: 67 + 58 → 15, 64 + 57 → 11. Такой вариант отличался
        // от ответа больше чем на треть в 42% случаев и отбрасывался, не считая.
        // Теперь эта ошибка моделируется честно — см. tenDecoyFor.
        pushStructural(structural, a - b, correctAnswer, isNegative);
    } else if (opKey === 'sub') {
        const noBorrowMag = noBorrowSub(a, b);
        if (noBorrowMag !== null) {
            const signedNoBorrow = correctAnswer < 0 ? -noBorrowMag : noBorrowMag;
            pushStructural(structural, signedNoBorrow, correctAnswer, isNegative);
        }
        pushStructural(structural, b - a, correctAnswer, isNegative);
        pushStructural(structural, a + b, correctAnswer, isNegative);
    } else if (opKey === 'mul') {
        // Частичное произведение — ошибка «перемножил только два». Она бывает
        // ТОЛЬКО у троек, а тройки живут только в отрицательных: там наружу
        // отдаётся разложение, и a — это произведение первых двух.
        // В положительных a — просто множитель, и как вариант он никуда не
        // годится: «4 × 26 = 104» с кнопкой «4» тратит слот впустую. Замер
        // показывал множитель среди вариантов в 38–42% примеров.
        if (isNegative) pushStructural(structural, a, correctAnswer, isNegative);
        pushStructural(structural, a * (b + 1), correctAnswer, isNegative);
        pushStructural(structural, a * (b - 1), correctAnswer, isNegative);
        pushStructural(structural, (a + 1) * b, correctAnswer, isNegative);
        pushStructural(structural, (a - 1) * b, correctAnswer, isNegative);
        pushStructural(structural, a + b, correctAnswer, isNegative);
    } else if (opKey === 'div') {
        pushStructural(structural, correctAnswer + 1, correctAnswer, isNegative);
        pushStructural(structural, correctAnswer - 1, correctAnswer, isNegative);
        if (Math.abs(b) <= Math.abs(correctAnswer) * 3 + 10) {
            pushStructural(structural, b, correctAnswer, isNegative); // делитель как ответ
        }
        pushStructural(structural, a, correctAnswer, isNegative);     // делимое как ответ
        pushStructural(structural, a * b, correctAnswer, isNegative); // умножение вместо деления
    }

    structural = shuffleArray(structural);

    const used = new Set([correctAnswer]);
    const result = []; // числа и, возможно, строка 'NO_SOLUTION'

    // Через этот фильтр проходит каждый вариант: невозможный ответ ученик
    // отбрасывает не считая, и слот пропадает зря (см. plausibleWhole).
    const plausible = (v) => plausibleWhole(opKey, a, b, v, isNegative);

    // ===== ОТРИЦАТЕЛЬНЫЕ: НАБОР МОДУЛЕЙ НЕ ДОЛЖЕН УКАЗЫВАТЬ НА ОТВЕТ =====
    //
    // Знаковая ловушка стояла первым приоритетом, а остальные варианты имели
    // разные модули. Получалось «−540, 540, −630, −84»: пара одинаковых цифр
    // ровно одна, и верный ответ ВСЕГДА в ней. Значит, считать не нужно —
    // найди пару, примени правило знаков, готово.
    //
    // Замер: близнец присутствовал в 96,8–100% примеров, и ответ определялся
    // парой в 93–100%. В отрицательном сложении и вычитании — ровно 100%, то
    // есть весь раздел проходился мимо арифметики. Это объясняло и стопроцентную
    // точность при трёх секундах на пример.
    //
    // Чиним не убиранием ловушки — она нужна, — а тем, что пар становится ДВЕ:
    // «−540, 540, −630, 630». Теперь близнец не подсказывает ничего: чтобы
    // выбрать, нужно знать и модуль (это арифметика), и знак (это правило).
    // Каждое знание отсекает половину, вместе они дают ответ — ровно те два
    // умения, которые тема и проверяет.
    //
    // Исключение — примеры с вариантом «Нет решения»: там числовых слотов всего
    // три, на две пары их не хватает. В этом случае модули делаются РАЗНЫМИ, без
    // единой пары. Это не подсказка: «Нет решения» ученик и так видит на экране.
    if (isNegative && correctAnswer !== 0 && count === 3 && !includeNoSolutionDecoy) {
        const mag = Math.abs(correctAnswer);
        const mags = [];
        priority.concat(structural).forEach(v => {
            const m = Math.abs(v);
            if (m === 0 || m === mag || mags.indexOf(m) >= 0) return;
            if (plausible(m) && plausible(-m)) mags.push(m);
        });
        // Структурных ловушек может не оказаться вовсе: у отрицательного
        // сложения разрядные приманки отключены, и весь список — это один
        // «a − b», который иногда совпадает с ответом по модулю. Тогда второй
        // модуль строим сами, рядом с ответом. Замер до этого: на первой звезде
        // общий путь подхватывал 10% примеров и возвращал в них старую утечку.
        // Пара обязана заставлять СЧИТАТЬ, а не только выбирать знак. Если
        // второй модуль далеко от ответа («−41 − (−53) = 12» против 94), он
        // отбрасывается без счёта, и вопрос вырождается в одно правило знаков.
        // Замер: у вычитания так выходило в 78–90% примеров, потому что весь
        // его список ловушек в этом режиме — это «a + b».
        //
        // Поэтому в большинстве случаев берём модуль рядом с ответом, а
        // содержательным дальним ловушкам («умножил вместо деления») оставляем
        // меньшую долю — без них исчез бы целый вид ошибки.
        const NEAR_PAIR_SHARE = 0.7;
        const near = mags.filter(m => Math.abs(m - mag) <= Math.max(2, mag * 0.5));
        let pool = mags;
        if (near.length > 0 && Math.random() < NEAR_PAIR_SHARE) pool = near;
        else if (near.length === 0 && Math.random() < NEAR_PAIR_SHARE) pool = [];
        let second = pool.length > 0 ? pool[randInt(0, pool.length - 1)] : 0;

        // Две пары закрывают подсказку ПО ЗНАКУ, но не по последней цифре.
        // Модули ±m дают цифры d и 10−d, поэтому верную последнюю цифру имел
        // ровно один вариант: замер давал 72–94% примеров, и «посчитай единицы»
        // работало здесь ровно так же, как работало в положительных.
        //
        // Лечится выбором второго модуля, сравнимого с первым по модулю десять:
        // тогда все четыре варианта дают цифры d, 10−d, d, 10−d, и одной
        // единицы мало. Смещение кратно десяти — это та же ошибка «не учёл
        // десяток», что и в положительных.
        if (mag >= 20) {
            const tens = [];
            [10, 20, 10 * Math.min(Math.abs(a), Math.abs(b) || 10)].forEach(st => {
                if (!st || st % 10 !== 0) return;
                [mag + st, mag - st].forEach(v => {
                    if (v > 0 && v !== mag && tens.indexOf(v) < 0) tens.push(v);
                });
            });
            if (tens.length) second = tens[randInt(0, tens.length - 1)];
        }

        if (!second) {
            const spread = Math.max(2, Math.round(mag * 0.2));
            for (let i = 0; i < 40 && !second; i++) {
                let d = randInt(-spread, spread);
                if (d === 0) d = 1;
                const cand = mag + d;
                if (cand > 0 && cand !== mag) second = cand;
            }
        }
        if (second) return shuffleArray([-correctAnswer, second, -second]);
        // Совсем невозможный случай — падаем в общий путь: пустых кнопок быть не должно.
    }

    // Когда на экране «Нет решения», числовых слотов остаётся три — на две пары
    // их не хватает. Тогда модули должны стать РАЗНЫМИ: одна пара снова была бы
    // подсказкой. Здесь это и обеспечивается — в том числе для знаковой ловушки,
    // которая иначе прошла бы первым приоритетом и вернула ровно ту пару.
    const noPairMode = isNegative && includeNoSolutionDecoy;
    const usedMags = new Set([Math.abs(correctAnswer)]);
    const magFree = (v) => !noPairMode || typeof v !== 'number' || !usedMags.has(Math.abs(v));
    const take = (v) => {
        result.push(v); used.add(v);
        if (typeof v === 'number') usedMags.add(Math.abs(v));
    };

    // Сначала — обязательный приоритет 1 (знак, нулевые кейсы умножения)
    for (const v of priority) {
        if (result.length >= count) break;
        if (!used.has(v) && plausible(v) && magFree(v)) take(v);
    }

    // "Нет решения" — отдельная сущность, тоже приоритет 1
    if (includeNoSolutionDecoy && result.length < count && !used.has('NO_SOLUTION')) {
        take('NO_SOLUTION');
    }

    // Затем — структурные дистракторы, заполняем всё, что осталось (до 3 слотов)
    for (const v of structural) {
        if (result.length >= count) break;
        if (!used.has(v) && plausible(v) && magFree(v)) take(v);
    }

    // Остаток — случайный разброс. Масштаб считаем и от ответа, и от величины
    // операндов примера, чтобы разброс не выглядел нелепо мелким при больших числах
    const scaleBase = Math.max(Math.abs(correctAnswer), Math.abs(a), Math.abs(b));
    const deltaMax = Math.max(3, Math.round(scaleBase * 0.15));
    let guard = 0;
    while (result.length < count && guard < 200) {
        guard++;
        let delta = randInt(-deltaMax, deltaMax);
        if (delta === 0) delta = 1;
        const fake = correctAnswer + delta;
        if (!isNegative && fake < 0) continue;
        if (fake === a || fake === b) continue;
        if (used.has(fake)) continue;
        if (!plausible(fake)) continue;
        if (!magFree(fake)) continue;
        take(fake);
    }

    // Последний рубеж. Правдоподобных чисел рядом может физически не хватить:
    // у 2 − 1 меньше уменьшаемого лежит ровно одно число, а слотов три. Пустой
    // кнопки на экране быть не должно, поэтому после исчерпания попыток фильтр
    // снимается. Случай редкий и только на самых маленьких примерах.
    let widen = deltaMax;
    let relax = false;
    // Счётчик попыток. Со снятым фильтром слоты набираются за пару десятков
    // шагов, так что предел не срабатывает никогда — он стоит не ради обычного
    // случая, а ради невозможного. Если ответ вдруг окажется не числом, вся
    // арифметика вокруг него даёт NaN, а Set считает NaN равным самому себе:
    // used.has(fake) вечно true, ни один вариант не проходит, и цикл крутится
    // без выхода. В браузере это не ошибка, а замерший телефон посреди занятия.
    // Так и случилось, когда divisorAllowed(0) пропускал делитель 0: пример
    // 0 ÷ 0 доходил сюда и вешал страницу наглухо.
    let attempts = 0;
    const attemptLimit = deltaMax * 4 + 500;
    while (result.length < count && attempts < attemptLimit) {
        attempts++;
        widen++;
        // Сняв фильтр, начинаем поиск заново от ответа: иначе к моменту снятия
        // счётчик уже уехал далеко, и в вариантах появляется нелепое «5 − 1 = 68».
        if (!relax && widen > deltaMax + 60) { relax = true; widen = 1; }
        const fake = correctAnswer + widen * (Math.random() < 0.5 ? -1 : 1);
        if (!isNegative && fake < 0) continue;
        if (fake === a || fake === b) continue; // выровнено с основным циклом выше
        if (used.has(fake)) continue;
        if (!relax && !plausible(fake)) continue;
        // Модуль-дубль отбрасываем, пока фильтр не снят: после снятия важнее
        // не оставить пустую кнопку, чем сохранить набор без пар.
        if (!relax && !magFree(fake)) continue;
        take(fake);
    }

    // Сюда попадаем только если предел выше сработал, то есть от ответа
    // отсчитать варианты не вышло вовсе. Пустой кнопки на экране быть не
    // должно, поэтому добираем чем угодно различным: пример всё равно уже
    // испорчен, но игра продолжается и ученик видит экран, а не зависание.
    let filler = 1;
    while (result.length < count) {
        if (!used.has(filler)) take(filler);
        filler++;
    }

    return result;
}

function buildNoSolutionOptions(dividend, isNegative) {
    const used = new Set();
    const opts = [];

    function tryAdd(v) {
        if (v === undefined || v === null || !Number.isFinite(v)) return false;
        v = Math.round(v);
        if (!isNegative && v < 0) return false;
        if (used.has(v)) return false;
        used.add(v);
        opts.push(v);
        return true;
    }

    tryAdd(0);
    tryAdd(dividend);

    const deltaMax = Math.max(5, Math.round(Math.abs(dividend) * 0.3));
    let guard = 0;
    while (opts.length < 3 && guard < 60) {
        guard++;
        tryAdd(dividend + randInt(-deltaMax, deltaMax));
    }
    let widen = deltaMax;
    while (opts.length < 3) {
        widen++;
        tryAdd(dividend + widen * (Math.random() < 0.5 ? -1 : 1));
    }

    return opts;
}

function generateProblem(opKey, level, isNegative) {
    if (!isNegative) {
        if (opKey === 'add') return genAddPositive(level);
        if (opKey === 'sub') return genSubPositive(level);
        if (opKey === 'mul') return genMulPositive(level);
        return genDivPositive(level);
    } else {
        if (opKey === 'add') return genAddNegative(level);
        if (opKey === 'sub') return genSubNegative(level);
        if (opKey === 'mul') return genMulNegative(level);
        return genDivNegative(level);
    }
}

// ===================== ДРОБИ: АРИФМЕТИКА =====================
function gcd(a, b) {
    a = Math.abs(a); b = Math.abs(b);
    while (b) { const t = a % b; a = b; b = t; }
    return a || 1;
}
function simplifyFrac(num, den) {
    if (den < 0) { den = -den; num = -num; }
    const g = gcd(num, den) || 1;
    return { num: num / g, den: den / g };
}
function fracAdd(f1, f2) { return simplifyFrac(f1.num * f2.den + f2.num * f1.den, f1.den * f2.den); }
function fracSub(f1, f2) { return simplifyFrac(f1.num * f2.den - f2.num * f1.den, f1.den * f2.den); }
function fracMul(f1, f2) { return simplifyFrac(f1.num * f2.num, f1.den * f2.den); }
function fracDiv(f1, f2) { return simplifyFrac(f1.num * f2.den, f1.den * f2.num); }

// Смешанное число ↔ дробь. sign применяется ко всей величине целиком
// (т.е. -1¾ хранится как num=-7, den=4, а не как отдельно "минус целая часть").
function mixedToFrac(whole, num, den, sign) {
    return { num: sign * (whole * den + num), den };
}
// Обратное преобразование: magnitude-раскладка на знак/целую часть/остаток.
// whole и remNum здесь всегда неотрицательные — знак хранится отдельно в sign.
function toMixedParts(f) {
    const sign = f.num < 0 ? -1 : 1;
    const absNum = Math.abs(f.num);
    const whole = Math.floor(absNum / f.den);
    const remNum = absNum % f.den;
    return { sign, whole, remNum, den: f.den };
}

