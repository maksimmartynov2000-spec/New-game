function pickFromShares(rows) {
    let r = Math.random();
    for (let i = 0; i < rows.length; i++) {
        r -= rows[i][1];
        if (r < 0) return rows[i][0];
    }
    return rows[rows.length - 1][0];
}

// Пара множителей по имени группы. Общая для обоих режимов: положительный
// вызывает её через свои доли, отрицательный — через свои. Двузначное на
// однозначное сюда не входит: у него своя механика полос, и в долях
// отрицательных его не бывает — genMulPositive разбирает этот случай сам.
//
// Незнакомое имя группы не роняет генератор. Опечатка в таблице долей — это
// ошибка разработчика, и ловить её должны проверки (см. «генератор знает
// каждую группу, названную в долях»), а не ученик посреди занятия: исключение
// здесь означало бы, что пример не отрисуется вовсе и экран замрёт.
// Ноль в отрицательном разделе не учит ничему: у нуля нет знака, и «0 × (−7)» —
// это пример на положительное умножение, случайно сюда попавший. Он же
// единственный случай, где у ответа не бывает знакового близнеца, а на близнецах
// держится весь набор вариантов ответа (см. buildDistractors).
const NEG_TRIV_MUL = MUL_GROUPS.triv.filter(pr => pr[0] !== 0 && pr[1] !== 0);
const NEG_TRIV_DIV = DIV_GROUPS.triv.filter(pr => pr[0] !== 0);

function mulPairForGroup(group, noZero) {
    if (group === 'triv' && noZero) return pickMulFact(NEG_TRIV_MUL);
    if (group === 'two') {
        return pickMulFact(Math.random() < MUL_TWO_EXT_SHARE
            ? MUL_GROUPS.twoExt : MUL_GROUPS.two);
    }
    if (group === 'tworound') return pickMulFact(MUL_TWO_ROUND);
    return pickMulFact(MUL_GROUPS[group] || MUL_GROUPS.small);
}

// --- "МЕШОК" ЗНАКОВ: гарантирует, что все 4 комбинации (+/+ +/- -/+ -/-)
// встретятся равномерно, но порядок внутри цикла остаётся случайным ---
function createSignBag() { return { queue: [] }; }
function nextSignPair(bag) {
    if (bag.queue.length === 0) {
        bag.queue = shuffleArray(['++', '+-', '-+', '--']);
    }
    const token = bag.queue.pop();
    return [token[0] === '+' ? 1 : -1, token[1] === '+' ? 1 : -1];
}

