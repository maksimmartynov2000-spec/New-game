// ===================== ДЕЛЕНИЕ ПОЛОЖИТЕЛЬНЫХ =====================
//
// Деление — зеркало умножения: 56 ÷ 7 = 8 и 7 × 8 = 56 это один и тот же факт.
// Поэтому groups, доли и полосы берутся у умножения целиком, а не изобретаются
// заново: всё, что мы там настроили, деление получает даром.
//
// Но зеркало ломается в трёх местах, и каждое пришлось учесть.
//
// ПЕРВОЕ. Один факт умножения даёт ДВЕ задачи на деление — кроме квадратов.
// 6 × 7 = 42 даёт 42÷6 и 42÷7, а 6 × 6 = 36 — только 36÷6. Значит, ядро из
// шести фактов превращается в девять задач. И если брать равномерно по фактам,
// вся доля квадрата ложится на единственную задачу: 36÷6 выпадает ВДВОЕ ЧАЩЕ
// соседей — точная инверсия того бага, из-за которого в умножении квадраты
// выпадали вдвое реже. Причина одна: считали не то, что выдаём. Поэтому здесь
// перечисляются именно ЗАДАЧИ НА ДЕЛЕНИЕ.
//
// ВТОРОЕ. Перестановки нет. В умножении 7 × 8 и 8 × 7 — один факт в двух видах,
// и порядок был оформлением. В делении 56÷7 и 56÷8 — разные задачи с разными
// ответами, и выбор делителя это содержание, а не вид.
//
// ТРЕТЬЕ. Особый случай не один, а четыре: 7÷1 (переписать), 7÷7 (правило),
// 0÷7 (правило) и 7÷0 (нет решения). Последнее — единственное, что надо помнить
// всерьёз, и держать его на 10% всю игру, как было, незачем.
function divProblems(pairs) {
    const seen = new Set(), out = [];
    pairs.forEach(pair => {
        const c = pair[0] * pair[1];
        [[c, pair[0]], [c, pair[1]]].forEach(pr => {
            const dividend = pr[0], divisor = pr[1];
            if (!divisorAllowed(divisor)) return;
            const key = dividend + '/' + divisor;
            if (seen.has(key)) return;
            seen.add(key);
            out.push([dividend, divisor]);
        });
    });
    return out;
}

