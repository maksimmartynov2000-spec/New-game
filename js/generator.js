function lcm(a, b) { return (a * b) / gcd(a, b); }

// Числитель правильной, уже несократимой дроби (условие примера всегда в сокращённом виде)
function randFracProper(den) {
    if (den <= 1) return 0;
    let n, guard = 0;
    do {
        n = randInt(1, den - 1);
        guard++;
    } while (gcd(n, den) !== 1 && guard < 20);
    if (gcd(n, den) !== 1) n = 1; // гарантированный несократимый фолбэк
    return n;
}

