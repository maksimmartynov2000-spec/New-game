// ===================== УМНОЖЕНИЕ ПОЛОЖИТЕЛЬНЫХ =====================
//
// Полосы из сложения сюда не переносятся. Там сложность росла по двум осям —
// размер чисел и переход через десяток. У умножения первая ось почти ничего не
// значит: 9 × 9 = 81 мельче, чем 50 × 2 = 100, но труднее в разы, потому что
// первое надо помнить, а второе видно.
//
// Ось здесь одна: КАКИМ ПРИЁМОМ до факта добираются. По ней таблица распадается
// на пять непересекающихся групп, которые в сумме дают ровно 36 фактов от 2×2
// до 9×9 — без дыр и без наложений (это проверяется тестом). Каждый факт
// принадлежит той группе, чей приём до него доводит: 2 × 7 — это удвоение, а не
// «семёрки»; 9 × 7 — девятки, а не «семёрки».
//
// И тогда видно главное: фактов, до которых не доводит НИКАКОЙ приём, на всю
// таблицу остаётся шесть — 6×6, 6×7, 6×8, 7×7, 7×8, 8×8. Ради них и существует
// третья звезда. Нынешний генератор выдавал их в 8,3% случаев на 3★ и не выдавал
// больше нигде: 7 × 8 встречалось 1,85 раза на сотню ответов за всю игру.
//
// Факты перечисляются СПИСКОМ и берутся равномерно, а не собираются как «выбрать
// множитель, потом партнёра». Во втором случае 6 × 7 рождается двумя путями
// (из шестёрок и из семёрок), а 6 × 6 — одним, и квадраты систематически выпадают
// вдвое реже соседей. Эта ошибка есть в нынешнем генераторе; здесь её нет.
function mulFacts(rows, partners) {
    const seen = new Set(), out = [];
    rows.forEach(a => partners.forEach(b => {
        const lo = Math.min(a, b), hi = Math.max(a, b);
        const key = `${lo},${hi}`;
        if (seen.has(key)) return;
        seen.add(key);
        out.push([lo, hi]);
    }));
    return out;
}

