-- Есть ли у каждого аккаунта живая сессия. Запусти это ПЕРЕД тем, как убирать
-- старый вход по паролю (это последний, шестой пункт списка правок).
--
-- Зачем: приложение ходит на сервер двумя способами — по токену сессии (основной)
-- и по паролю (запасной, для устройства, которое ещё не успело обменять пароль на
-- токен). Убрать запасной путь безопасно только тогда, когда у КАЖДОГО устройства
-- токен уже есть. Иначе устройство, которое давно не открывали, окажется заперто
-- снаружи: пароль на нём есть, а серверу он больше не нужен.
--
-- Как читать: у каждого аккаунта, которым реально пользуются, должна быть хотя бы
-- одна живая сессия. Ноль сессий у аккаунта, который заходил недавно, — повод не
-- торопиться: значит, какое-то устройство до сих пор ходит по паролю.

select p.code                                        as "логин",
       coalesce(p.state->>'profileLabel', '')        as "имя",
       coalesce(p.account_type, p.state->>'accountType', '?') as "тип",
       count(s.token_hash) filter (where s.expires_at > now()) as "живых сессий",
       max(s.last_seen_at)                           as "последняя сессия",
       p.updated_at                                  as "последняя запись прогресса"
  from citadel_progress p
  left join citadel_session s on s.code = p.code
 group by p.code, p.state, p.account_type, p.updated_at
 order by "живых сессий", p.code;
