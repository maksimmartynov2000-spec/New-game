-- =====================================================================
--  ВЫЙТИ НА ДРУГИХ УСТРОЙСТВАХ
-- ---------------------------------------------------------------------
--  Каждый вход с нового устройства или из нового окна заводит отдельную
--  сессию, и живёт она 90 дней. Они накапливаются: на аккаунте репетитора
--  их набралось семнадцать. Само по себе это не поломка, но каждая такая
--  сессия — действующий ключ от аккаунта, и если одно из тех устройств
--  потеряно или отдано, ключ продолжает работать.
--
--  Эта функция гасит все сессии аккаунта, КРОМЕ той, из которой её позвали.
--  Так человек не может случайно запереть сам себя: устройство, с которого
--  нажали кнопку, остаётся в игре, а на остальных попросят войти заново.
--
--  Пароль не меняется: он у ученика и так есть, и смысл тут не в нём, а в
--  том, чтобы отозвать выданные ключи.
--
--  Запускать можно на работающем приложении и сколько угодно раз подряд.
-- =====================================================================

create or replace function session_logout_others(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_code text := session_owner(p_token);
  v_hash text;
  v_closed int;
begin
  if v_code is null then
    return jsonb_build_object('ok', false, 'error', 'bad_session');
  end if;
  -- Ту же самую sha256, что лежит в таблице: сам токен нигде не хранится.
  v_hash := encode(digest(p_token, 'sha256'), 'hex');
  delete from citadel_session where code = v_code and token_hash <> v_hash;
  get diagnostics v_closed = row_count;
  return jsonb_build_object('ok', true, 'closed', v_closed);
end;
$$;
