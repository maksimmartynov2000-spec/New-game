--  Этого файла долго не было, и это была настоящая дыра: таблицу
--  citadel_progress завели руками в панели Supabase ещё до первой миграции,
--  и в репозитории её не существовало нигде. То есть по репозиторию базу
--  нельзя было восстановить: миграции ссылаются на таблицу, которой они не
