--     4. supabase/access-codes.sql     — коды доступа к разделам
--     5. supabase/student-access.sql   — выдача доступов напрямую
--     6. supabase/stats-report.sql     — сводки для репетитора
--     7. supabase/exam.sql             — вводный экзамен
--     8. supabase/owner-columns.sql    — владелец ученика в колонке
--     9. supabase/password-length.sql  — минимум восемь символов
--    10. supabase/exam-cap.sql         — потолок выдачи у экзамена
--    11. supabase/logout-others.sql    — выход на других устройствах
--    12. supabase/restore.sql          — восстановление ученика из копии
--    13. supabase/drop-legacy.sql      — убрать старый путь по паролю
--    14. supabase/lock-internals.sql   — закрыть внутренности от anon
--
--  Последние два обязательны и на новой базе: старые функции заводит второй шаг,
--  а права анонимной роли Supabase раздаёт сам, каждой новой функции. Без этих
--  шагов рядом с новой дверью останется старая, а внутренности будут видны наружу.
--
--  И отдельно, ОДИН РАЗ, когда в базе ещё нет ни одного аккаунта:
