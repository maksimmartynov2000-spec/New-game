-- Хеширование паролей. На Supabase расширение живёт в схеме extensions,
-- поэтому все функции ниже по цепочке держат её в search_path.
create extension if not exists pgcrypto;

-- =====================================================================
--  citadel_progress — одна строка на человека, ученика и репетитора одинаково
-- ---------------------------------------------------------------------
--  state — весь прогресс одним документом: счётчики, журнал по дням, темы,
--  достижения, пазл, коллекция, настройки. Разбирать его на таблицы незачем:
--  читается он всегда целиком и всегда одним человеком.
--
--  owner_code и account_type ЗАВЕДЕНЫ ОТДЕЛЬНЫМИ КОЛОНКАМИ намеренно, хотя
--  те же значения лежат и внутри state. Причина в том, что state приходит от
--  клиента и записывается как есть: пока владелец жил только в нём, ученик мог
--  одним вызовом переписать его и отвязаться от репетитора вместе со
--  статистикой и сбросом пароля. Колонки клиенту недоступны, и при каждом
--  сохранении оба поля в state принудительно заменяются на их значения
--  (см. pin_identity в owner-columns.sql).
-- =====================================================================
create table if not exists citadel_progress (
  code          text primary key,                          -- логин; его придумывает репетитор
  password_hash text,                                      -- bcrypt; самого пароля в базе нет
  owner_code    text,                                      -- чей это ученик; null у репетитора
  account_type  text,                                      -- 'self' | 'linked'
  state         jsonb not null default '{}'::jsonb,        -- весь прогресс одним документом
  updated_at    timestamptz not null default now()
);

create index if not exists citadel_progress_owner_idx on citadel_progress (owner_code);

-- Прямого доступа к таблице нет ни у кого: публичный ключ не может прочитать
-- или записать ни строки. Единственный вход — SECURITY DEFINER функции из
-- миграций. Политик здесь нет намеренно: включённая RLS без политик и означает
-- «закрыто всем», и это ровно то, что нужно.
alter table citadel_progress enable row level security;
