test('новые подсказки собираются на всех языках и не печатают ответ', () => {
    // Ответ — это результат последнего счёта; он не должен стоять в подсказке
    // числом, которого нет в самом примере (правило: за шаг до ответа).
    const cases = [
        ['спутал модули', 'add', { a: -8, b: 3 }, -5, -11],
        ['спутал модули', 'sub', { a: 3, b: 8 }, -5, 11],
        ['спутал модули', 'sub', { a: -7, b: 3 }, -10, -4],
        ['спутал модули', 'add', { a: 7, b: 3 }, 10, 4],
        ['двойной минус', 'sub', { a: 5, b: -3 }, 8, 2],
        ['минус в скобках', 'add', { a: 5, b: -3 }, 2, 8]
    ];
    LANGS.forEach(lang => {
        const box = loadHints({ HINT_CONTENT: CONTENT });
        box.LANG = lang;
        cases.forEach(([kind, op, p, correct, chosen]) => ['game', 'review'].forEach(form => {
            const got = box.R.hintText(form, kind, meta(op), p, correct, chosen);
            assert(got && !/%\d/.test(got), `[${lang}] «${kind}» ${form}: «${got}»`);
            assert(got.indexOf('-') < 0 || /[A-Za-z]-[A-Za-z]/.test(got), `[${lang}] дефис вместо минуса: «${got}»`);
            const own = [Math.abs(p.a), Math.abs(p.b)];
            const nums = (got.match(/\d+/g) || []).map(Number).filter(n => own.indexOf(n) < 0);
            assert(nums.indexOf(Math.abs(correct)) < 0, `[${lang}] «${kind}» ${form} печатает ответ: «${got}»`);
        }));
    });
});

