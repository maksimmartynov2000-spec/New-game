// шаблон с подстановками обязан собрать ровно утверждённую строку. «Общий знаменатель
// тут не нужен» из первой пачки снят тогда же: в игре его случай не встречается.
const Fr = (s) => { const [n, d = '1'] = String(s).split('/'); return { num: Number(n), den: Number(d) }; };
const Mx = (s) => { const [w, f] = s.split(' '); const q = Fr(f); return { num: Number(w) * q.den + q.num, den: q.den }; };
const fracMeta = (op) => ({ opKey: op, category: 'fraction' });
const AR = (a, b) => ({ f1: Fr(a), f2: Fr(b) });
const CV = (whole, properNum, den) => ({ whole, properNum, den });
const OF = (fracNum, fracDen, N) => ({ fracNum, fracDen, N, k: N / fracDen });
const FRAC_BOXES = {};
function fracBox(lang) {
    if (!FRAC_BOXES[lang]) { FRAC_BOXES[lang] = loadHints({ HINT_CONTENT: CONTENT }); FRAC_BOXES[lang].LANG = lang; }
    return FRAC_BOXES[lang];
}
function fracHint(form, kind, op, problem, correct, chosen, lang) {
    const val = (x) => (typeof x === 'string' ? (x.indexOf(' ') > 0 ? Mx(x) : Fr(x)) : x);
    return fracBox(lang || 'ru').R.hintText(form, kind, fracMeta(op), problem, val(correct), val(chosen));
}

