test('дроби: на примерах генератора — без остатков подстановок, без ответа в игре, до 80 знаков', () => {
    // Полный генератор и разбор — как в приложении. Варианты «почти» (та же величина)
    // в арифметике подсказки не получают: игра засчитывает их как «не сократил».
    const sb = { console, Math, Number, Object, Array, String, JSON, Set, Map, Date, isNaN, parseInt, parseFloat,
        localStorage: { getItem: () => null, setItem() {}, removeItem() {} }, navigator: {},
        window: { HINT_CONTENT: CONTENT }, document: { documentElement: { lang: 'ru' }, getElementById: () => null } };
    sb.globalThis = sb;
    vm.createContext(sb);
    vm.runInContext(['js/i18n.js', 'js/topics.js', 'js/generator.js', 'js/mistakes.js']
        .map(f => fs.readFileSync(path.join(ROOT, f), 'utf8')).join('\n'), sb, { filename: 'app' });
    const G = sb;
    const gen = (op, lvl) => op === 'simplify' ? G.generateSimplifyProblem(lvl)
        : op === 'toMixed' ? G.generateToMixedProblem(lvl) : op === 'toImproper' ? G.generateToImproperProblem(lvl)
        : op === 'fracOfNumber' ? G.generateFracOfNumberProblem(lvl) : G.generateFractionProblem(op, lvl, false);
    const fakes = (op, lvl, p) => op === 'simplify' ? G.buildSimplifyDistractors(p.given, p.answer, 3, p.m)
        : (op === 'toMixed' || op === 'toImproper') ? G.buildMixedConvertDistractors(p, 3)
        : op === 'fracOfNumber' ? G.buildFracOfNumberDistractors(p, 3)
        : G.buildFractionDistractors(op, p.f1, p.f2, p.answer, false, 3, lvl);
    const bad = [];
    let shown = 0, wrong = 0;
    ['ru', 'en', 'fr', 'de'].forEach(lang => {
        vm.runInContext(`LANG = ${JSON.stringify(lang)}`, sb);
        ['add', 'sub', 'mul', 'div', 'simplify', 'toMixed', 'toImproper', 'fracOfNumber'].forEach(op => {
            for (let lvl = 1; lvl <= 5; lvl++) for (let i = 0; i < 40; i++) {
                const p = gen(op, lvl);
                const meta = { opKey: op, category: 'fraction', level: lvl };
                fakes(op, lvl, p).forEach(f => {
                    const arith = ['add', 'sub', 'mul', 'div'].indexOf(op) >= 0;
                    if (arith && f.num * p.answer.den === p.answer.num * f.den) return;
                    wrong++;
                    const kind = G.classifyMistake(meta, p, p.answer, f);
                    const game = G.hintText('game', kind, meta, p, p.answer, f);
                    const review = G.hintText('review', kind, meta, p, p.answer, f);
                    if (game) shown++;
                    [game, review].forEach(x => { if (x && /%\d|(^|[\s(])-\d/.test(x)) bad.push(`[${lang}] ${kind}: ${x}`); });
                    if (!game) return;
                    if (game.length > 80) bad.push(`[${lang}] ${kind}: ${game.length} знаков — ${game}`);
                    // Ответ в строке игры — запись целиком, а не цифра внутри другой записи.
                    const toks = game.match(/\d+ \d+\/\d+|\d+\/\d+|\d+/g) || [];
                    if (op === 'fracOfNumber') {
                        const own = [p.fracNum, p.fracDen, p.N].map(String);
                        if (toks.indexOf(String(p.answer)) >= 0 && own.indexOf(String(p.answer)) < 0) bad.push(`[${lang}] ответ в игре: ${game}`);
                    } else {
                        const ans = op === 'toMixed' ? G.fracHintMixed(p.answer) : G.fracHintStr(p.answer);
                        const own = op === 'simplify' ? [G.fracHintStr(p.given)] : p.f1 ? [G.fracHintStr(p.f1), G.fracHintStr(p.f2)] : [];
                        if (toks.indexOf(ans) >= 0 && own.indexOf(ans) < 0) bad.push(`[${lang}] ответ в игре: ${game}`);
                    }
                });
            }
        });
    });
    // Без этого проверка могла бы пройти впустую: на пустых строках ошибок нет.
    assert(shown > wrong * 0.6, `подсказок слишком мало: ${shown} из ${wrong}`);
    const found = [...new Set(bad)];
    eq(found.slice(0, 5).join(' | '), '', `плохих строк: ${found.length}`);
});

