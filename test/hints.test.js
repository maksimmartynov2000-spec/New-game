group('Десятичные');

// Тексты утвердил репетитор 03.11 — на примерах. Здесь те же примеры: шаблон с
// подстановками обязан собрать ровно утверждённую строку, иначе где-то разъехались
// слова или числа. Где утверждённую строку пришлось поменять, это сказано рядом.
const D = (s) => { const [w, f = ''] = s.split(','); return { intVal: Number(w + f), dp: f.length }; };
const decMeta = (op) => ({ opKey: op, category: 'decimal' });
function decHint(form, kind, op, a, b, chosen, lang) {
    const box = loadHints({ HINT_CONTENT: CONTENT });
    box.LANG = lang || 'ru';
    const d1 = D(a), d2 = D(b);
    const correct = vm.runInContext(`(${JSON.stringify(op)} === 'add' ? decAdd : ${JSON.stringify(op)} === 'sub' ? decSub : ${JSON.stringify(op)} === 'mul' ? decMul : null)`, box);
    let ans = correct ? correct(d1, d2) : null;
    if (op === 'div') ans = vm.runInContext(`stripTrailingZeros({ intVal: ${Math.round(d1.intVal / Math.pow(10, d1.dp) / (d2.intVal / Math.pow(10, d2.dp)) * 1e6)}, dp: 6 })`, box);
    return box.R.hintText(form, kind, decMeta(op), { d1, d2 }, ans, D(chosen));
}

